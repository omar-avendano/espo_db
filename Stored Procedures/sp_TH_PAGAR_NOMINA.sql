ALTER PROCEDURE [dbo].[sp_TH_PAGAR_NOMINA]
@IDNOMINA INT,
@USERNAME VARCHAR(60) 
AS
BEGIN
SET NOCOUNT ON

DECLARE
    @IDMOVGC INT =0,
    @BASE INT =0,
    @PORCENTAJE DECIMAL(10,2) =0,
    @ESTADO CHAR(1)='',
    @IDCENTROCOSTO INT=0,
    @CODCENTROCOSTO INT=NULL,
    @NUMCUENTA VARCHAR(20)=N'',
    @NATURALEZA CHAR(1)=N'',
    @NROASIENTO INT =0

SELECT @ESTADO=ESTADO
FROM TH_NOMINALIQC 
WHERE IDNOMINALIQC=@IDNOMINA

IF LEN(@ESTADO)>0 AND @ESTADO='C'
    BEGIN  
        SET @ESTADO =''

        DECLARE @PERIODO INT,@PERIODOPAGO INT,
        @VALOR_EPS_EMPLEADO DECIMAL(18, 2)=0,
        @VALOR_AFP_EMPLEADO DECIMAL(18, 2)=0,
        @DIAS_EPS INT=0,
        @NUMIDENTIFICACION VARCHAR(20)=N'',
        @EMPLEADO VARCHAR(200)=N'',
        @SUBSIDIOTRANSPORTE DECIMAL(18, 2)=0,
        @SUELDO DECIMAL(18, 2)=0,
        @SUELDOBASICO DECIMAL(18, 2)=0,
        @TOTALDEVENGADO DECIMAL(18, 2)=0,
        @SOLIDARIDAD DECIMAL(18, 2)=0,
        @LIBRANZA DECIMAL(18, 2)=0,
        @RETENCION DECIMAL(18, 2)=0,
        @OTROSDESCUENTOS DECIMAL(18, 2)=0,
        @TOTDEDUCCIONES DECIMAL(18, 2)=0,
        @NETOPAGAR DECIMAL(18, 2)=0,
        @TOTALNETOPAGAR DECIMAL(18, 2)=0,
        @IDTRANSACCION DECIMAL(18, 2)=1,
        @CREDITO DECIMAL(18, 2)=0,
        @FECHATRCR DATE=CAST(GETDATE() AS DATE),
        @NUMDOCUME INT=0,
        @CODDOCUMEREL VARCHAR(5)=N'NOM',
        @NUMDOCUMEREL VARCHAR(30)=STR(@IDNOMINA)

        --Traer Periodo
        SELECT @PERIODO=PERIODO
        FROM TH_NOMINALIQC
        WHERE IDNOMINALIQC = @IDNOMINA

        --Crear registro de cabecera      

        SELECT @NUMDOCUME=MAX(NUMDOCUME)+1 FROM GC_MOV_C WHERE GC_MOV_C.CODDOCUME='TRA'

        INSERT INTO GC_MOV_C ( CODDOCUME, IDTERCERO,CODDOCUMEREL, NUMDOCUME,NUMDOCUMEREL, FECHA, DESCRIPCION, PERIODO, CONTABILIZADO, DEBITO, CREDITO,INACTIVO, USUARIOTRCR, FECHATRCR ) 
        VALUES ( 'TRA', @NUMIDENTIFICACION,@CODDOCUMEREL, @NUMDOCUME,@NUMDOCUMEREL, @FECHATRCR, 'CAUSACION PAGO NÓMINA', @PERIODOPAGO, '0', @NETOPAGAR, @NETOPAGAR,0, 'SPASIENTO', @FECHATRCR )

        SET @IDMOVGC = SCOPE_IDENTITY();

        --Cursor para recorer los empleados
        DECLARE cursor_nomina CURSOR FOR
        SELECT 
            BASE.VALOR_EPS_EMPLEADO,
            BASE.VALOR_AFP_EMPLEADO,
            DIAS_EPS,
            HV.NUMIDENTIFICACION,
            CONCAT(HV.PRIMERNOMBRE, ' ', HV.SEGUNDONOMBRE, ' ', HV.PRIMERAPELLIDO, ' ', HV.SEGUNDOAPELLIDO) AS EMPLEADO,
            VALOR_SUBSIDIOTRANSPORTE,
            CASE WHEN BASE.SUELDO > 0 THEN BASE.SUELDO ELSE C.SALARIO END AS SUELDO,
            BASE.BASE_EPS AS SUELDOBASICO,
            BASE.BASE_EPS + BASE.VALOR_SUBSIDIOTRANSPORTE AS TOTALDEVENGADO,
            (SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND IDCONCEPTO IN (3)) AS SOLIDARIDAD,
            (SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND IDCONCEPTO IN (8)) AS LIBRANZA,
            (SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND IDCONCEPTO IN (10)) AS RETENCION,
            (SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND IDCONCEPTO NOT IN (10, 8) AND COD_NOVEDAD <> '') AS OTROSDESCUENTOS,
            (BASE.VALOR_EPS_EMPLEADO + BASE.VALOR_AFP_EMPLEADO
            + ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND COD_NOVEDAD <> ''), 0) 
            + ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND IDCONCEPTO IN (3)), 0)) AS TOTDEDUCCIONES,
            ((BASE.BASE_EPS + BASE.VALOR_SUBSIDIOTRANSPORTE)
            - ISNULL((BASE.VALOR_EPS_EMPLEADO + BASE.VALOR_AFP_EMPLEADO), 0)
            - ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND IDCONCEPTO IN (3)), 0)
            - ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC = BASE.IDNOMINALIQC AND IDHOJAVIDA = BASE.IDHOJAVIDA AND DIAS=BASE.DIAS_EPS AND COD_NOVEDAD <> ''), 0)) AS NETOPAGAR
        FROM TH_NOMINA_BASE BASE
        LEFT JOIN TH_HV HV ON HV.IDHOJAVIDA = BASE.IDHOJAVIDA
        LEFT JOIN TH_CONTRATOHV C ON C.IDHOJAVIDA = HV.IDHOJAVIDA AND C.IDCONTRATOHV = BASE.IDCONTRATOHV
        LEFT JOIN TH_PARAMETROANUAL P ON P.IDPARAMETROANUAL = C.IDPARAMETROANUAL
        WHERE BASE.IDNOMINALIQC = @IDNOMINA

        OPEN cursor_nomina

        FETCH NEXT FROM cursor_nomina INTO 
            @VALOR_EPS_EMPLEADO,
            @VALOR_AFP_EMPLEADO,
            @DIAS_EPS,
            @NUMIDENTIFICACION,
            @EMPLEADO,
            @SUBSIDIOTRANSPORTE,
            @SUELDO,
            @SUELDOBASICO,
            @TOTALDEVENGADO,
            @SOLIDARIDAD,
            @LIBRANZA,
            @RETENCION,
            @OTROSDESCUENTOS,
            @TOTDEDUCCIONES,
            @NETOPAGAR

        WHILE @@FETCH_STATUS = 0
        BEGIN
            
            SET @PERIODOPAGO = @PERIODO / 100
            SET @NROASIENTO=@IDTRANSACCION
            SET @CREDITO=@NETOPAGAR
            SET @TOTALNETOPAGAR=@TOTALNETOPAGAR+@NETOPAGAR
            
            --Movimientos de detalle

            --Debito
            SET @NUMCUENTA='250501'
            SET @NATURALEZA='D'
            INSERT INTO GC_MOV_D ( IDMOVGC, IDTERCERO, IDCENTROCOSTO, CODCENTROCOSTO, NUMCUENTA, NOMCUENTA, NATURALEZA, NROASIENTO, DESCRIPCION, VALOR, BASERET, RETENCION, PERIODO ) 
                            VALUES ( @IDMOVGC, @NUMIDENTIFICACION, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NUMCUENTA, @NATURALEZA, @NROASIENTO, '', @CREDITO,  @BASE, @PORCENTAJE, @PERIODOPAGO )
            --Credito
            SET @NUMCUENTA='11100504'
            SET @NATURALEZA='C'
            INSERT INTO GC_MOV_D ( IDMOVGC, IDTERCERO, IDCENTROCOSTO, CODCENTROCOSTO, NUMCUENTA, NOMCUENTA, NATURALEZA, NROASIENTO, DESCRIPCION, VALOR, BASERET, RETENCION, PERIODO ) 
                            VALUES ( @IDMOVGC, @NUMIDENTIFICACION, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NUMCUENTA, @NATURALEZA, @NROASIENTO, '', @CREDITO,  @BASE, @PORCENTAJE, @PERIODOPAGO )

            SET @IDTRANSACCION=@IDTRANSACCION+1

            FETCH NEXT FROM cursor_nomina INTO 
                @VALOR_EPS_EMPLEADO,
                @VALOR_AFP_EMPLEADO,
                @DIAS_EPS,
                @NUMIDENTIFICACION,
                @EMPLEADO,
                @SUBSIDIOTRANSPORTE,
                @SUELDO,
                @SUELDOBASICO,
                @TOTALDEVENGADO,
                @SOLIDARIDAD,
                @LIBRANZA,
                @RETENCION,
                @OTROSDESCUENTOS,
                @TOTDEDUCCIONES,
                @NETOPAGAR

        END

        CLOSE cursor_nomina
        DEALLOCATE cursor_nomina

        UPDATE GC_MOV_C
            SET CREDITO=@TOTALNETOPAGAR 
        WHERE IDMOVGC=@IDMOVGC

        UPDATE TH_NOMINALIQC 
        SET ESTADO='X'
        WHERE IDNOMINALIQC=@IDNOMINA

    END

END