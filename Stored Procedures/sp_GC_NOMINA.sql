ALTER PROCEDURE [dbo].[sp_GC_NOMINA]
(
  @PERIODO int
)
AS
BEGIN
SET NOCOUNT ON
	--Variables para recibir datos del cursor
	DECLARE @IDPREDIO int, @IDNOMINALIQC int, @IDHOJAVIDA int
	DECLARE @IDCICLO int, @NROASIENTO int
	DECLARE @CODDOCUME VARCHAR(10), @NUMDOCUME VARCHAR(30)  
	DECLARE @NUMFACTURA VARCHAR(50), @IDTERCERO int, @IDCENTROCOSTO int, @CODCENTROCOSTO varchar(10)
	DECLARE @STRNROOBLIGACION VARCHAR(20), @NUMCUENTA varchar(30), @NOMCUENTA varchar(255), @BASERET decimal(18,2)

	DECLARE @IDCONCEPTO int, @CONCEPTO varchar(256), @NROOBLIGACION varchar(60), @VALOR decimal(18,2), @IDMOVCART int
	DECLARE @CREDITO decimal(18,2),@DEBITO decimal(18,2), @NATURALEZA char(1)
    DECLARE @TERCERO varchar(50), @FECHA date, @ASIENTOMOVIMIENTO int
    DECLARE @DOCUMENTOTERCERO varchar(50), @DOCUMENTOANTERIORTERCERO varchar(50)
	
	--SET @PERIODO = 202301
    SET @TERCERO = 'NOMINA'
    SET @DOCUMENTOANTERIORTERCERO = '0'

    DELETE FROM GC_ASIENTO WHERE TPDOC = 'NOM' AND SUBSTRING ( REPLACE( convert(varchar(25), FECHACR, 120) , '-', '') ,0 , 7 ) = @PERIODO
    
    UPDATE TH_NOMINAMOVCNT
    SET CONTABILIZADO = '0'
    WHERE IDNOMINALIQC IN ( 
        SELECT IDNOMINALIQC FROM TH_NOMINALIQC  
        WHERE SUBSTRING ( REPLACE( convert(varchar(25), PERIODO, 120) , '-', '') ,0 , 7 ) = @PERIODO
    );

	--Recorrer personal que se va a incluir en la nomina
	DECLARE CurNomina CURSOR FOR
 
 
    SELECT  T.IDNOMINALIQC, 'NOM', T.COD_TERCERO AS DOCUMENTOTERCERO, C.IDCENTROCOSTO,  
    T.CENTRO, T.COD_CUENTA, P.AUXILIAR AS NOMCUENTA, T.NATURALEZA, T.VALOR,
    L.FECHALIQUIDACION, T.NUMASIENTO
    FROM TH_NOMINAMOVCNT T
    LEFT JOIN GC_CENTROCOSTO C ON C.CODIGO = T.CENTRO
    LEFT JOIN GC_DM_PUC P ON P.CUENTAAUXILIAR = T.COD_CUENTA
    LEFT JOIN TH_NOMINALIQC L ON L.IDNOMINALIQC = T.IDNOMINALIQC
    WHERE T.CONTABILIZADO = '0' 
    AND SUBSTRING ( CAST( L.PERIODO AS varchar(10) ) ,0 , 7 ) = @PERIODO
    ORDER BY T.COD_TERCERO ASC


	OPEN CurNomina
	FETCH NEXT FROM CurNomina INTO  @IDNOMINALIQC,  @CODDOCUME,  @DOCUMENTOTERCERO, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NOMCUENTA, @NATURALEZA, @VALOR, @FECHA, @ASIENTOMOVIMIENTO

	WHILE (@@FETCH_STATUS = 0) 
	BEGIN	

        SET @DEBITO = 0
        SET @CREDITO = 0

        --PRINT @DOCUMENTOANTERIORTERCERO 

        IF (@DOCUMENTOANTERIORTERCERO <> @DOCUMENTOTERCERO) BEGIN
            --PRINT N'DIFERENTE'
            SELECT @NUMDOCUME = ISNULL( MAX(NUMDOC), 0 ) + 1 FROM GC_ASIENTO WHERE TPDOC = 'NOM'
            SET @DOCUMENTOANTERIORTERCERO = @DOCUMENTOTERCERO
            SET @NROASIENTO = 0
        END
        

        --trer número de documento de nómina
        IF (@NATURALEZA = 'D') BEGIN
            SET @DEBITO = @VALOR
        END
        ELSE BEGIN
            SET @CREDITO = @VALOR
        END
        
        SET @NROASIENTO = @NROASIENTO + 1

		--PRINT N'NATURALEZA:'+ @NATURALEZA +' VALOR:'+STR(@VALOR) + ' NOMCUENTA:' + @NOMCUENTA + '  DOCUMENTO ' + @DOCUMENTOTERCERO + '  ASIENNTO ' + STR(@NROASIENTO) + '  NUMDOC ' + STR(@NUMDOCUME)

        --insertar asientos
        EXEC sp_GC_ASIENTO_CREATE @NROASIENTO, @IDCENTROCOSTO, @CODCENTROCOSTO, @TERCERO, @DOCUMENTOTERCERO, @CODDOCUME, @NUMDOCUME, @FECHA, @NUMCUENTA, @DEBITO, @CREDITO, 0, 0.0

        --actualizar causacion a contabilizado
        UPDATE TH_NOMINAMOVCNT SET CONTABILIZADO = 1 WHERE IDNOMINALIQC = @IDNOMINALIQC AND NUMASIENTO = @ASIENTOMOVIMIENTO 


		FETCH NEXT FROM CurNomina INTO @IDNOMINALIQC,  @CODDOCUME,  @DOCUMENTOTERCERO, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NOMCUENTA, @NATURALEZA, @VALOR, @FECHA, @ASIENTOMOVIMIENTO
	END 

	CLOSE CurNomina
	DEALLOCATE CurNomina	 


END
