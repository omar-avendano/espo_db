ALTER PROCEDURE [dbo].[sp_TH_LIQVACACIONES_HV]
@IDLIQUIDACIONVACACIONESC INT,
@FECHALIQUIDACION DATE,
@USERNAME VARCHAR(60) ,
@IDHOJAVIDA INT
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE 
    @TOTALDEVENGADOPERIODO decimal(10,2) 	=0,
    @FECHAINICIO DATE				        =NULL,
    @NUMDIASLIQUIDAR	INT 				=0,
    @DIASCOMPENSAR	INT 				=0,
    @DIAS_SOLICITADOS	INT 				=0,
    @NUMDIASNOVEDADES	INT 				=0,
	@PROCESAR			BIT					=1,
    @NUMEROCONTRATO VARCHAR(50)             ='',
    @SALARIO decimal(10,2)                  =0,
    @APLICASUBTRAN BIT                      =0,
    @SUBSIDIOTRANSPORTE decimal(10,2)       =0,
    @POR_VACACIONES real                         =0,
    @CODIGOEMP varchar(15)                  =''
    DECLARE @VALOR_MOV decimal(10,2)		=0
    DECLARE @FECHAINICIOCONTRATO DATE       = NULL
    DECLARE @ULTFECHAVACACIONES DATE        = NULL
    DECLARE @FECHAPIVOT DATE                = NULL
    DECLARE @FORMULA NVARCHAR(250)=''

    --Traer informacion actual de contrato
    SELECT @CODIGOEMP=HV.CODIGO,@SALARIO=(CHV.SALARIO),@APLICASUBTRAN=CHV.SUBSIDIOTRANSPORTE, @SUBSIDIOTRANSPORTE=IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0),
            @FECHAINICIOCONTRATO=dbo.GetDateIniContract ( CHV.IDCONTRATOHV ),            
            @POR_VACACIONES=PA.POR_VACACIONES
    FROM dbo.TH_HV HV
        INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
        --JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHALIQUIDACION)
        INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.IDPARAMETROANUAL=CHV.IDPARAMETROANUAL
    WHERE HV.ESTADOHV=1 AND HV.IDHOJAVIDA=@IDHOJAVIDA
    
    SET @FECHAINICIO=@FECHAINICIOCONTRATO 
    --Identificar rango de fechas de liquidacion
    SELECT @DIAS_SOLICITADOS=SUM(DIAS_SOLICITADOS)
        FROM TH_LIQUIDACIONVACACIONES DET
        WHERE DET.IDHOJAVIDA=@IDHOJAVIDA 
        and FECHA_INICIO>= @FECHAINICIOCONTRATO AND FECHA_INICIO<= @FECHALIQUIDACION

    --Procesar Registros
    IF @PROCESAR =1
        BEGIN
            SET @TOTALDEVENGADOPERIODO = @SALARIO
            
            --Traer dias de novedades que afectan vacaciones
            EXEC @NUMDIASNOVEDADES=sp_TH_DIASNOVEDADESPERSONAL @IDHOJAVIDA,@FECHAINICIO ,@FECHALIQUIDACION,'AFECTA_VACACIONES',@IDLIQUIDACIONVACACIONESC;
            
            SELECT @NUMDIASLIQUIDAR=dbo.Days360( @FECHAINICIO, DATEADD(day, 1, @FECHALIQUIDACION) )
            /* PRINT 'DIAS LIQ:'+STR(@NUMDIASLIQUIDAR)
            PRINT 'DIAS NOV:'+STR(@NUMDIASNOVEDADES)
            PRINT 'DIAS SOL:'+STR(@DIAS_SOLICITADOS) */
            --Descontar dias de novedades si hay
            IF @NUMDIASNOVEDADES>0
                BEGIN
                    SET @NUMDIASLIQUIDAR=@NUMDIASLIQUIDAR-@NUMDIASNOVEDADES
                END
            --Descontar dias de novedades si hay
            IF @DIAS_SOLICITADOS>0
                BEGIN
                    SET @NUMDIASLIQUIDAR=@NUMDIASLIQUIDAR-(@DIAS_SOLICITADOS*24)

                END
                
            SET @DIASCOMPENSAR=(15*@NUMDIASLIQUIDAR)/360
            SET @VALOR_MOV=(@TOTALDEVENGADOPERIODO*@NUMDIASLIQUIDAR)/720

            IF @VALOR_MOV<0
                BEGIN
                    SET @VALOR_MOV=0
                END 
  
            --Verificar si hay novedad de aumento transitorio de salario
            --Se quita por solicitud de Ana y se desactiva que novedades de aumento afecen vacaciones
                /*
                DECLARE @VALORNOV DECIMAL(10,2)=0,@TOTALDIASNOVEDAD INT =0,@VALORLIQADD DECIMAL(10,2)=0,@DIASCOMPENSARADD INT=0
                SELECT @VALORNOV=VALOR,
                    @TOTALDIASNOVEDAD=IIF(FECHAFIN < @FECHALIQUIDACION, DATEDIFF(day,IIF(FECHAINICIO<@FECHAINICIO,@FECHAINICIO,FECHAINICIO) ,DATEADD(day, 1, FECHAFIN)),
                    DATEDIFF(day,IIF(FECHAINICIO<@FECHAINICIO,@FECHAINICIO,FECHAINICIO) ,DATEADD(day, 1, @FECHALIQUIDACION)))              
                    FROM TH_NOVEDAD
                    INNER JOIN TH_DM_SUBTIPONOVEDAD ON TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=TH_NOVEDAD.IDSUBTIPONOVEDAD
                    WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=8   
                    AND @FECHAINICIO < FECHAFIN
                    AND @FECHALIQUIDACION > FECHAINICIO
                
                IF @TOTALDIASNOVEDAD>0 AND @VALORNOV>0
                    BEGIN
                        --Calcular liq aumento
                        SET @DIASCOMPENSARADD=(15*@TOTALDIASNOVEDAD)/360
                        SET @VALORLIQADD=(@VALORNOV*@TOTALDIASNOVEDAD)/720
                        SET @VALOR_MOV=(@TOTALDEVENGADOPERIODO*(@NUMDIASLIQUIDAR))/720

                        --Recalcular valores periodo
                        SET @VALOR_MOV = @VALOR_MOV+@VALORLIQADD                        

                    END 
                    */
            SET @FORMULA='FINI:'+CONVERT(varchar,@FECHAINICIO,23)+' FFIN:'+CONVERT(varchar,@FECHALIQUIDACION,23)+' vlr salario: '+STR(@TOTALDEVENGADOPERIODO)+' VALOR BASE :'+STR(@VALOR_MOV)+' * DIAS: '+STR(@NUMDIASLIQUIDAR)+' DIAS NOV:'+ISNULL(STR(@NUMDIASNOVEDADES),'')+' DIAS SOL:'+ISNULL(STR(@DIAS_SOLICITADOS),'')+' '

            INSERT INTO TH_LIQUIDACIONVACACIONES
            (IDHOJAVIDA,FECHA_INICIO,FECHA_SOLICITUD,FECHA_FINAL,FECHA_APROBACION,DIAS_SOLICITADOS,OBSERVACIONES,NUMEROCONTRATO,LIQUIDA,DIAS_APROBADOS,REMUNERACION,DIAS_PENDIENTES,DIAS_REAL,DEVENGADO,FECHA_DOCUMENTO,COD_DOCUMENTO,NUM_DOCUMENTO,HORA,CONTABILIZADO,ES_PAGA,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
            VALUES
                (@IDHOJAVIDA,@FECHAINICIO,@FECHALIQUIDACION,@FECHALIQUIDACION,@FECHALIQUIDACION,@DIASCOMPENSAR,'LIQ FINAL',@NUMEROCONTRATO,1,@DIASCOMPENSAR,@SALARIO,0,@DIASCOMPENSAR,@VALOR_MOV,GETDATE(),'01','01',CONVERT (TIME, GETDATE()),1,0,@USERNAME,GETDATE(),@USERNAME,GETDATE())
            
            --LIQ D 
            INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,FORMULAPLICAR)
            VALUES (@IDLIQUIDACIONVACACIONESC,@IDHOJAVIDA,48,'PG-VACACIO ',@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250803','250504','123',GETDATE(),@FORMULA) 

        END

END
