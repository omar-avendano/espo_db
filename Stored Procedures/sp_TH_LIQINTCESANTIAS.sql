ALTER PROCEDURE [dbo].[sp_TH_LIQCESANTIAS]
@PERIODO INT,
@FECHALIQUIDACION DATETIME ,
@USERNAME VARCHAR(60) ,
@OBSERVACIONES NVARCHAR(MAX) ,
@MENSAJE varchar(150) OUTPUT
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE @IDLIQUIDACIONCESANTIASC int    =0
    
	--Variables para recibir datos del cursor
	
    BEGIN
        IF NOT EXISTS (SELECT * FROM TH_NOMINALIQC 
                        WHERE PERIODO = @PERIODO and MOD_ORIGEN='LIQCES')
        BEGIN
            --Crear registro cabecera liquidaciones
            INSERT INTO dbo.TH_NOMINALIQC (PERIODO, FECHALIQUIDACION, FECHAMOVIMIENTO, MOD_ORIGEN, ESTADO, DESCRIPCION, EMPLEADOS_LIQUIDADOS, OBSERVACIONESLIQUIDACION, USUARIOTRCR,FECHATRCR, USUARIOTRED, FECHATRED)
            VALUES (@PERIODO,@FECHALIQUIDACION,GETDATE(),'LIQCES','L','LIQUIDACION CESANTIAS ',1,'LIQUIDACION CESANTIAS',@USERNAME,GETDATE(),@USERNAME,GETDATE())

            /* INSERT INTO TH_LIQUIDACIONCESANTIASC (PERIODO, FECHA_LIQUIDACION, OBSERVACIONES,ESTADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
            VALUES (@PERIODO,@FECHALIQUIDACION,@OBSERVACIONES,'L',@USERNAME,@FECHALIQUIDACION,@USERNAME,@FECHALIQUIDACION) */

            SET @IDLIQUIDACIONCESANTIASC= SCOPE_IDENTITY()

            IF @IDLIQUIDACIONCESANTIASC>0
                BEGIN          
                    
                    exec sp_TH_LIQCESANTIAS_DET @IDLIQUIDACIONCESANTIASC,@PERIODO ,@USERNAME
                END
                

        END

        IF @IDLIQUIDACIONCESANTIASC > 0
            BEGIN
                SET @MENSAJE='Registro agregado correctamente'
            END
        ELSE 
            BEGIN
                SET @MENSAJE='Registro ya existe' 
            END

    END

END
GO