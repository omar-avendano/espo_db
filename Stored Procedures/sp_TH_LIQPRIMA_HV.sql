ALTER PROCEDURE [dbo].[sp_TH_LIQPRIMA_HV]
@IDLIQUIDACIONPRIMAC INT,
@IDHOJAVIDA INT,
@FECHALIQUIDACION DATE,
@USERNAME VARCHAR(60) 
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE 
    @TOTALDEVENGADOPERIODO decimal(10,2) 	=0,
    @FECHAINICIO DATE				        =NULL,
    @NUMDIASLIQUIDAR	INT 				=0,
	@PROCESAR			BIT					=0,
    @NUMEROCONTRATO VARCHAR(50)             ='',
    @SALARIO decimal(10,2)                  =0,
    @APLICASUBTRAN BIT                      =0,
    @SUBSIDIOTRANSPORTE decimal(10,2)       =0,
    @POR_PRIMA real                         =0,
    @CODIGOEMP varchar(15)                  ='',
    @NUMDIASNOVEDADES	INT 				=0;
    DECLARE @VALOR_MOV decimal(10,2)		=0
    DECLARE @FECHAINICIOCONTRATO DATE       = NULL
    DECLARE @FECHAINICIOSISTEMA DATE       = '2021-01-01'
    DECLARE @ULTFECHAPRIMA DATE             = NULL
    DECLARE @FECHAPIVOT DATE             = NULL
    DECLARE @FORMULA NVARCHAR(250)='';

    --Traer informacion actual de contrato
    SELECT @CODIGOEMP=HV.CODIGO,@SALARIO=(CHV.SALARIO),@APLICASUBTRAN=CHV.SUBSIDIOTRANSPORTE, @SUBSIDIOTRANSPORTE=IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0),
            @FECHAINICIOCONTRATO=CHV.FECHAINICIO,            
            @POR_PRIMA=PA.POR_PRIMA
    FROM dbo.TH_HV HV
        INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
        --JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHALIQUIDACION)
        INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHALIQUIDACION)
    WHERE HV.ESTADOHV=1 AND HV.IDHOJAVIDA=@IDHOJAVIDA;
    
    --Identificar rango de fechas de liquidacion
    --Taer fecha ultima liquidacion
    SELECT TOP 1 @ULTFECHAPRIMA=DET.FECHA_PRIMA
        FROM TH_LIQUIDACIONPRIMAD DET
        JOIN TH_NOMINALIQC CAB ON DET.IDLIQUIDACIONPRIMAC=CAB.IDNOMINALIQC
        WHERE DET.IDHOJAVIDA=@IDHOJAVIDA 
        ORDER BY DET.IDLIQUIDACIONPRIMAC DESC;
    
    IF @ULTFECHAPRIMA IS NOT NULL
        BEGIN
            -- Si hay liquidacion identificar fecha inicio liquidacion
            IF @ULTFECHAPRIMA < @FECHALIQUIDACION  
                BEGIN
                      
                    SET @PROCESAR=1 
                    IF @FECHAINICIOCONTRATO > @ULTFECHAPRIMA AND @FECHAINICIOCONTRATO < @FECHALIQUIDACION
                        BEGIN
                            SET @FECHAINICIO=@FECHAINICIOCONTRATO
                        END 
                    ELSE
                        BEGIN
                            SET @FECHAINICIO=DATEADD(d, 1, EOMONTH(@ULTFECHAPRIMA))
                        END
                END
        END
    ELSE 
        BEGIN
            -- Si no hay liquidacion anterior traer fecha de inicio de contrato  como fecha inicio liquidacion
            IF @FECHAINICIOCONTRATO > @FECHAINICIOSISTEMA
                BEGIN 
                    SET @FECHAINICIO=@FECHAINICIOCONTRATO 
                END
            ELSE
                BEGIN
                    SET @FECHAINICIO=DATEADD(d, 1, EOMONTH('2020-12-31')) 
                END
              
            SET @PROCESAR=1 
        END

    --Validar si hubo cambio de año para apicar sueldo base
    /* IF YEAR(@FECHAINICIO)< YEAR(@FECHALIQUIDACION)
        BEGIN
            DECLARE @FECHAFIN DATE =NULL

		    SET @FECHAFIN=CAST(str(YEAR(@FECHAINICIO))+'-12-31' as date)

            IF YEAR(@FECHAINICIO) < YEAR(@FECHAINICIOCONTRATO)
                BEGIN 
                    --Treaer informacion de salario del contrato anterior
                    SELECT TOP 1 @NUMEROCONTRATO=TH_CONTRATOHV.NUMEROCONTRATO,
                        @SALARIO=(PA.SALARIOMINIMO*TH_CONTRATOHV.PORCENTAJESALARIOBASE),
                        @SUBSIDIOTRANSPORTE=IIF(TH_CONTRATOHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0)
                    FROM TH_CONTRATOHV
                    JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHAINICIO)
                    WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_CONTRATOHV.ESTADO=0 AND YEAR(TH_CONTRATOHV.FECHAINICIO)=YEAR(@FECHAINICIO)
                    ORDER BY TH_CONTRATOHV.IDCONTRATOHV DESC
                END
            
            SET @TOTALDEVENGADOPERIODO = @SALARIO+@SUBSIDIOTRANSPORTE

            SELECT @NUMDIASLIQUIDAR=dbo.Days360( @FECHAINICIO, DATEADD(day, 1, @FECHAFIN) )
				
            SET @VALOR_MOV=(@TOTALDEVENGADOPERIODO*@NUMDIASLIQUIDAR)/360
            
            INSERT INTO dbo.TH_LIQUIDACIONPRIMAD 
                (IDLIQUIDACIONPRIMAC,IDHOJAVIDA,NUMEROCONTRATO,FECHA_INICIOLIQUIDACION,FECHA_PRIMA,DIAS_PRIMA,BASE_PRIMA,VALOR_PRIMA,OBSERVACIONES,CONTABILIZADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
            VALUES 
                (@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,@NUMEROCONTRATO,@FECHAINICIO,@FECHAFIN,@NUMDIASLIQUIDAR,@TOTALDEVENGADOPERIODO,@VALOR_MOV,'LIQ PRIMA ',0,@USERNAME,GETDATE(),@USERNAME,GETDATE()) 

			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION)
			VALUES (@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,46,'PG-PRIMASE',@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250804','250506','123',GETDATE()) A

            SET @FECHAINICIO = CAST(str(YEAR(@FECHALIQUIDACION))+'-01-01' as date)
                
        END     */
        
        --Procesar Registros
		IF @PROCESAR =1
			BEGIN
                SET @TOTALDEVENGADOPERIODO = @SALARIO+@SUBSIDIOTRANSPORTE;

                EXEC @NUMDIASNOVEDADES=sp_TH_DIASNOVEDADESPERSONAL @IDHOJAVIDA,@FECHAINICIO ,@FECHALIQUIDACION,'AFECTA_CESANTIAS',@IDLIQUIDACIONPRIMAC;
				
                
				SELECT @NUMDIASLIQUIDAR=@NUMDIASLIQUIDAR + dbo.Days360( @FECHAINICIO, DATEADD(day, 1, @FECHALIQUIDACION) )
				
                --Descontar dias de novedades si hay
				IF @NUMDIASNOVEDADES>0
                BEGIN
                    SET @NUMDIASLIQUIDAR=@NUMDIASLIQUIDAR-@NUMDIASNOVEDADES
                END
                
				SET @VALOR_MOV=(@TOTALDEVENGADOPERIODO*@NUMDIASLIQUIDAR)/360

                --Verificar si hay novedad de aumento transitorio de salario
                DECLARE @VALORNOV DECIMAL(10,2)=0,@TOTALDIASNOVEDAD INT =0,@VALORLIQADD DECIMAL(10,2)=0
                SELECT @VALORNOV=VALOR,
                    @TOTALDIASNOVEDAD=IIF(FECHAFIN < @FECHALIQUIDACION, DATEDIFF(day,IIF(FECHAINICIO<@FECHAINICIO,@FECHAINICIO,FECHAINICIO) ,DATEADD(day, 1, FECHAFIN)),
                    DATEDIFF(day,IIF(FECHAINICIO<@FECHAINICIO,@FECHAINICIO,FECHAINICIO) ,DATEADD(day, 1, @FECHALIQUIDACION)))              
                    FROM TH_NOVEDAD
                    INNER JOIN TH_DM_SUBTIPONOVEDAD ON TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=TH_NOVEDAD.IDSUBTIPONOVEDAD
                    WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=8   
                    AND @FECHAINICIO < FECHAFIN
                    AND @FECHALIQUIDACION > FECHAINICIO
                
                IF @TOTALDIASNOVEDAD>0 AND @VALORNOV>0
                    BEGIN
                        --Calcular liq aumento
                        SET @VALORLIQADD=(@VALORNOV*@TOTALDIASNOVEDAD)/360
                        SET @VALOR_MOV=(@TOTALDEVENGADOPERIODO*(@NUMDIASLIQUIDAR-@TOTALDIASNOVEDAD))/360

                        --Recalcular valores periodo
                        SET @VALOR_MOV = @VALOR_MOV+@VALORLIQADD                        

                    END 
				
                --Validar si viene numeros negativos
                IF @VALOR_MOV < 0
                    BEGIN
                        SET @VALOR_MOV=0
                    END 

                SET @FORMULA='FINI:'+CONVERT(varchar,@FECHAINICIO,23)+' FFIN:'+CONVERT(varchar,@FECHALIQUIDACION,23)+' vlr salario: '+STR(@TOTALDEVENGADOPERIODO)+' VALOR BASE :'+STR(@VALOR_MOV)+' * DIAS: '+STR(@NUMDIASLIQUIDAR)+' DIAS NOV:'+ISNULL(STR(@TOTALDIASNOVEDAD),'')+' '

				INSERT INTO dbo.TH_LIQUIDACIONPRIMAD 
					(IDLIQUIDACIONPRIMAC,IDHOJAVIDA,NUMEROCONTRATO,FECHA_INICIOLIQUIDACION,FECHA_PRIMA,DIAS_PRIMA,BASE_PRIMA,VALOR_PRIMA,OBSERVACIONES,CONTABILIZADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
        		VALUES 
					(@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,@NUMEROCONTRATO,@FECHAINICIO,@FECHALIQUIDACION,@NUMDIASLIQUIDAR,@TOTALDEVENGADOPERIODO,@VALOR_MOV,'LIQ DETALLE',0,@USERNAME,GETDATE(),@USERNAME,GETDATE()) 
				
				--LIQ D 
				INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,FORMULAPLICAR)
				VALUES (@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,46,'PG-PRIMASE',@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250804','250506','123',GETDATE(),@FORMULA) 

			END


END
