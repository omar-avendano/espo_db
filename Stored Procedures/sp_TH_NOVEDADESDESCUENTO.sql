ALTER PROCEDURE [dbo].[sp_TH_NOVEDADESDESCUENTO]
@ANIO CHAR(4),
@MES char(2),
@DIAINICIAL CHAR(2),
@DIAFINAL CHAR(2),
@IDHOJAVIDA INT,
@DIA INT ,--DIA quincena
@IDNOMINA INT, --ID Nomina
@DIASPERIODO INT =0,
@VALORDESCUENTOS decimal(12,2) OUTPUT
AS
BEGIN
    DECLARE @IDNOVEDAD int,@FECHAINICIO date, @FECHAFIN date ,@DIASPERIODOANTERIOR INT =0
	DECLARE @DIAAplicarNovDes int, @VALORNOVDES decimal(10,2),@IDTIPONOVEDAD int,
    @IDCONCEPTO int,@CODCONCEPTO varchar(20),@PERIODO int,@CUENTADEBITO NVARCHAR(20),
    @CUENTACREDITO NVARCHAR(20),@IDCONTRATOHV INT

    DECLARE @FECHAINICIOPERIODO DATE=CAST(CONCAT(@ANIO,'-',@MES,'-',@DIAINICIAL) as date)
    DECLARE @FECHAFINPERIODO DATE=NULL--CAST(CONCAT(@ANIO,'-',@MES,'-',@DIAFINAL) as date)

    IF @MES='02' AND @DIAFINAL='30'
		BEGIN
			SET @FECHAFINPERIODO=EOMONTH(@FECHAINICIOPERIODO) 
		END
	ELSE
		BEGIN
			SET @FECHAFINPERIODO=CAST(CONCAT(@ANIO,'-',@MES,'-',@DIAFINAL) as date)
		END

    Set @PERIODO= cast(Ltrim(Rtrim(@ANIO))+RIGHT('00' + Ltrim(Rtrim(@MES)),2)+Ltrim(Rtrim(str(@DIA))) as integer)
    --Traer info de contrato
    SELECT @IDCONTRATOHV=CHV.IDCONTRATOHV
	FROM dbo.TH_HV HV
	INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
    WHERE HV.IDHOJAVIDA=@IDHOJAVIDA
    --Cursor para recorrer novedades existentes
    
    DECLARE CurNovedadesDescuento CURSOR FOR
    SELECT ND.IDNOVEDAD,ND.IDTIPONOVEDAD,ND.FECHAINICIO,ND.FECHAFIN,ND.DIA,ND.VALOR,
        C.IDCONCEPTO,C.CODIGOCONCEPTO ,MC.CTA_DEBITO,MC.CTA_CREDITO
    FROM TH_NOVEDADDESCUENTO ND
    JOIN TH_DM_TIPONOVEDADDESCUENTO TN ON TN.IDTIPONOVEDAD=ND.IDTIPONOVEDAD
    JOIN TH_PR_CONCEPTO C ON C.IDCONCEPTO=TN.IDCONCEPTO
    JOIN TH_PR_MODOCONTABLE MC ON MC.COD_MODOCONTABLE=C.COD_MODOCONTABLE
    WHERE ND.FECHAINICIO <= @FECHAFINPERIODO
    AND ND.FECHAFIN >= @FECHAINICIOPERIODO
    AND ND.DIA=@DIA
    AND ND.IDHOJAVIDA=@IDHOJAVIDA
    AND ND.ESTADO=1
    
    OPEN CurNovedadesDescuento
    FETCH NEXT FROM CurNovedadesDescuento INTO @IDNOVEDAD,@IDTIPONOVEDAD,@FECHAINICIO,@FECHAFIN,@DIAAplicarNovDes,
    @VALORNOVDES,@IDCONCEPTO,@CODCONCEPTO,@CUENTADEBITO,@CUENTACREDITO
    
    --IF @@FETCH_STATUS <> 0  
        --PRINT ' IDNOJA:'+str(@IDHOJAVIDA)+' <<No tiene Novedades>>'   
        --PRINT ''   
    WHILE (@@FETCH_STATUS = 0) 
    BEGIN
         

        /* --Debito New
        INSERT INTO dbo.TH_NOMINALIQHV (IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALORPARCIAL,VALORTOTAL,NATURALEZA,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_LIQUIDO,CERRADO,CUENTA,CENTROCOSTO,SALDO,NUM_CUOTA,PERIODO)
        VALUES (@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALORNOVDES,@VALORNOVDES,'D',GETDATE(),GETDATE(),'ESPO',0,@CUENTADEBITO,'123',0,0,@PERIODO) 
        --Credito
        INSERT INTO dbo.TH_NOMINALIQHV (IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALORPARCIAL,VALORTOTAL,NATURALEZA,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_LIQUIDO,CERRADO,CUENTA,CENTROCOSTO,SALDO,NUM_CUOTA,PERIODO)
        VALUES (@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALORNOVDES,@VALORNOVDES,'C',GETDATE(),GETDATE(),'ESPO',0,@CUENTACREDITO,'123',0,0,@PERIODO)  */
        --LIQ D 
        /* IF @IDTIPONOVEDAD =6
            BEGIN
                SET @DIASPERIODO=dbo.Days360( @FECHAINICIOPERIODO, DATEADD(day, 1, @FECHAFINPERIODO) ) 

                SELECT @DIASPERIODOANTERIOR=DIAS_EPS
					FROM dbo.TH_NOMINA_BASE D
					JOIN dbo.TH_NOMINALIQC C on C.IDNOMINALIQC=D.IDNOMINALIQC
					WHERE D.IDHOJAVIDA=@IDHOJAVIDA AND C.MOD_ORIGEN='LIQNOM' AND MONTH(C.FECHALIQUIDACION)=@MES AND YEAR(C.FECHALIQUIDACION)=@ANIO

            END  */

        IF @DIASPERIODO =0
        BEGIN
                SELECT TOP 1 @DIASPERIODO=DIAS_EPS FROM TH_NOMINA_BASE WHERE IDNOMINALIQC=@IDNOMINA AND IDHOJAVIDA=@IDHOJAVIDA
        END 
        --PRINT ' IDNOJA:'+str(@IDHOJAVIDA)+' IDNOVEDAD:'+STR(@IDNOVEDAD)+' VALOR NOVEDAD:'+STR(@VALORNOVDES)+' DIAS PERIODO:'+STR(@DIASPERIODO)
        INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,COD_NOVEDAD,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,DIAS,IDCONTRATOHV)
        VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALORNOVDES,STR(@IDTIPONOVEDAD),GETDATE(),GETDATE(),'ESPO',0,@CUENTADEBITO,@CUENTACREDITO,'123',GETDATE(),STR(@IDNOMINA),@DIASPERIODO,@IDCONTRATOHV) 
        
        SET @VALORDESCUENTOS=@VALORDESCUENTOS-ISNULL(@VALORNOVDES,0)
        
        FETCH NEXT FROM CurNovedadesDescuento INTO @IDNOVEDAD,@IDTIPONOVEDAD,@FECHAINICIO,@FECHAFIN,@DiaAplicarNovDes,
        @VALORNOVDES,@IDCONCEPTO,@CODCONCEPTO,@CUENTADEBITO,@CUENTACREDITO
    END 
    
    CLOSE CurNovedadesDescuento
    DEALLOCATE CurNovedadesDescuento	
    
END