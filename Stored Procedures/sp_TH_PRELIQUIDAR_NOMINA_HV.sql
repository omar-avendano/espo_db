ALTER PROCEDURE [dbo].[sp_TH_PRELIQUIDAR_NOMINA_HV]
@IDNOMINA INT,
@IDHOJAVIDA INT,
@DIASPERIODO INT,
@SALARIO DECIMAL(10,2),
@SUELDOPERIODOPROVISIONES DECIMAL(10,2),
@AUXTRANSPORTE DECIMAL(10,2),
@USERNAME VARCHAR(60) 
AS
BEGIN
SET NOCOUNT ON
	
	DECLARE @DIA int

	DECLARE @FECHALIQUIDACION DATE,
			@SUELDOPERIODO DECIMAL(10,2),
            @NETOPAGAR decimal(10,2), 
    		@SALARIOMINIMOMES decimal(10,2),
     		@TOTALDEVENGADOPERIODO decimal(10,2),
			@TOTALNOMINA decimal(10,2) 
	DECLARE @VALOR_AFP_EMPLEADOR decimal(10,2)		=0,
			@VALOR_AFP_EMPLEADO decimal(10,2)		=0,
			@VALOR_EPS_EMPLEADOR decimal(10,2)		=0,
			@VALOR_EPS_EMPLEADO decimal(10,2)		=0,
			@VALOR_ARP decimal(10,2)				=0,
			@VALOR_CCF decimal(10,2)				=0,
			@VALOR_MOV decimal(10,2)				=0
	DECLARE 
			@IDTIPONOMINA int,
			@IDCONTRATOHV int,
			@APLICASUBTRAN BIT,
			@POR_PENSIONES real, 
			@POR_PENSIONEMPLEADO real,
			@POR_SALUD real, 
			@POR_SALUDEMPLEADO real,
			@POR_ARP real,
			@POR_CAJA real,
			@POR_CESANTIAS real,
			@POR_PRIMA real,
			@INT_CESANTIAS real, 
			@POR_VACACIONES real,
			@ANIO CHAR(4), 
			@MES int, 
			@DIAINICIAL char(2),
			@DIAFINAL char(2),
			@FORMULA NVARCHAR(250)=''

	DECLARE @MENSAJE NVARCHAR(300)					=''

	SELECT @DIA=SUBSTRING(RTRIM(LTRIM(STR(PERIODO))),7,2) ,@FECHALIQUIDACION=FECHALIQUIDACION,
		@ANIO=LEFT(LTRIM(RTRIM(STR(PERIODO))),4),
		@MES=SUBSTRING(RTRIM(LTRIM(STR(PERIODO))),5,2) ,
		@IDTIPONOMINA=IDTIPONOMINA,
		@DIAINICIAL=CASE 
						WHEN IDTIPONOMINA = 1 AND DAY(FECHALIQUIDACION) <= 15 
							THEN '01'
						WHEN IDTIPONOMINA = 1 AND DAY(FECHALIQUIDACION) > 15   
							THEN '16'
						WHEN IDTIPONOMINA = 2  
							THEN '01'
						ELSE   
							'01'
						END,
		@DIAFINAL=DAY(FECHALIQUIDACION)
		FROM TH_NOMINALIQC WHERE IDNOMINALIQC=@IDNOMINA
	
	DECLARE @charMES char(2)	=RIGHT('00' + rtrim(ltrim(str(@MES))), 2)

	SELECT @APLICASUBTRAN=CHV.SUBSIDIOTRANSPORTE,
			@POR_PENSIONES=PA.POR_PENSIONES,
			@POR_PENSIONEMPLEADO=PA.POR_PENSIONEMPLEADO,
			@POR_SALUD=PA.POR_SALUD,
			@POR_SALUDEMPLEADO=PA.POR_SALUDEMPLEADO,
			@POR_ARP=CARL.VALORINICIAL,
			@POR_CAJA=PA.POR_CAJA,
			@POR_CESANTIAS=PA.POR_CESANTIAS,
			@POR_PRIMA=PA.POR_PRIMA,
			@INT_CESANTIAS=PA.INT_CESANTIAS,
			@POR_VACACIONES=PA.POR_VACACIONES,
			@SALARIOMINIMOMES=PA.SALARIOMINIMO,
			@IDCONTRATOHV=CHV.IDCONTRATOHV
	  	  FROM dbo.TH_HV HV
	  INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
	  INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHALIQUIDACION)
	  INNER JOIN dbo.TH_DM_CLASERIESGOARL CARL ON CARL.ANIO=PA.ANIO AND CARL.CODIGO=CHV.CODIGORIESGOARL
	  WHERE HV.IDHOJAVIDA=@IDHOJAVIDA
	
	--SET @DIASPERIODO=DATEDIFF(day,@FECHAINICIOPERIODO ,DATEADD(day, 1, @FECHAFINPERIODO))
    SET @NETOPAGAR=0
	IF @IDTIPONOMINA=1 AND @DIASPERIODO > 15
		BEGIN
			SET @DIASPERIODO=15
		END 
	ELSE IF @IDTIPONOMINA=2 AND @DIASPERIODO > 30
		BEGIN
			SET @DIASPERIODO=30
		END 

    --Calcular si aplica subsidio de transporte 
     
    IF (@SALARIO>(ISNULL(@SALARIOMINIMOMES,0)*2))
        BEGIN
            SET @APLICASUBTRAN=0
            SET @AUXTRANSPORTE = 0
        END 
    ELSE
        BEGIN
            SET @APLICASUBTRAN=1
            --SET @AUXTRANSPORTE = (@AUXTRANSPORTE/30)*@DIASPERIODO
        END 

	SET @VALOR_MOV=0
	SET @SUELDOPERIODO = (@SALARIO/30)*@DIASPERIODO
	
	SET @TOTALDEVENGADOPERIODO = @SUELDOPERIODO+@AUXTRANSPORTE
		
	--PRINT N' ID EMP:'+STR(@IDHOJAVIDA)+' Sueldo:'+STR(@SUELDOPERIODO)+' Aux T:'+STR(@AUXTRANSPORTE)
       
	   	-- Novedades Generales
		/* EXECUTE dbo.sp_TH_NOVEDADES_HV 
							@IDNOMINA,
							@IDHOJAVIDA,
							@FECHAINICIOPERIODO,
							@FECHAFINPERIODO,
							@SALARIO,
							@DIASPERIODO OUTPUT,
							@SUELDOPERIODO OUTPUT,
							@AUXTRANSPORTE OUTPUT

		-- Descontar Vacaciones
		EXECUTE dbo.sp_TH_PRENOM_REVVACACIONES_HV
							@IDHOJAVIDA,
							@FECHAINICIOPERIODO,
							@FECHAFINPERIODO,
							@SALARIO,
							@DIASPERIODO OUTPUT,
							@SUELDOPERIODO OUTPUT,
							@AUXTRANSPORTE OUTPUT */
							
        SET @VALOR_AFP_EMPLEADOR = @SUELDOPERIODO*(@POR_PENSIONES)/100
		SET @VALOR_AFP_EMPLEADO = @SUELDOPERIODO*(@POR_PENSIONEMPLEADO)/100
		SET @VALOR_EPS_EMPLEADOR = (@SUELDOPERIODO*@POR_SALUD)/100
		SET @VALOR_EPS_EMPLEADO = (@SUELDOPERIODO*@POR_SALUDEMPLEADO)/100
		IF @SUELDOPERIODOPROVISIONES>0 SET @SUELDOPERIODOPROVISIONES=@SUELDOPERIODOPROVISIONES ELSE SET @SUELDOPERIODOPROVISIONES=@SUELDOPERIODO;
		SET @VALOR_ARP = (@SUELDOPERIODOPROVISIONES *@POR_ARP)/100
		SET @VALOR_CCF = (@SUELDOPERIODOPROVISIONES*@POR_CAJA)/100
        
        --PRINT N' Dias:'+str(@DIASPERIODO)+' Salud:'+str(@VALOR_EPS_EMPLEADO)+' Pension:'+STR(@VALOR_AFP_EMPLEADO)+' Sal pagar:'+STR(@TOTALSALARIOPAGARPERIODO)
        
        --Guardar Movimientos
        Declare @IDCONCEPTO INT 
        Declare @CODCONCEPTO VARCHAR(20) 
        --Sueldo  Cod 29
        SET @IDCONCEPTO =29
        SET @CODCONCEPTO ='DV-SUELDOB'
       
		--LIQ D 
		INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
        VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@SUELDOPERIODO,GETDATE(),GETDATE(),'ESPO',0,'510101','250501','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
		SET @TOTALNOMINA=@TOTALNOMINA+ISNULL(@SUELDOPERIODO,0)
        --Auxilio Transporte  Cod 28
		IF @APLICASUBTRAN=1
			BEGIN
				Set @IDCONCEPTO  =28
				Set @CODCONCEPTO  ='DV-SUBTRAN'	
				--LIQ D 
				INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
				VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@AUXTRANSPORTE,GETDATE(),GETDATE(),'ESPO',0,'510123','250501','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
				SET @TOTALNOMINA=@TOTALNOMINA+ISNULL(@AUXTRANSPORTE,0)
			END

        --Aportes Pension Empleado
			Set @IDCONCEPTO  =4
			Set @CODCONCEPTO  ='DD-APPENSI'			

			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_AFP_EMPLEADO,GETDATE(),GETDATE(),'ESPO',0,'250501','242518','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
			SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_AFP_EMPLEADO,0)
		--Salud
			Set @IDCONCEPTO  =5
			Set @CODCONCEPTO  ='DD-APSALUD'
			
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_EPS_EMPLEADO,GETDATE(),GETDATE(),'ESPO',0,'250501','242519','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
			SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_EPS_EMPLEADO,0)

		--Novedades de Descuento (Retencion)
		
		/* IF @DIA=30 
			BEGIN
				--Crear novedades de descuento
       			EXECUTE dbo.sp_TH_NOVEDADESDESCUENTO_HV
				   @IDNOMINA,
				   @IDHOJAVIDA,
				   @FECHAINICIOPERIODO,
				   @FECHAFINPERIODO,
				   @TOTALNOMINA OUTPUT
				
				--Fondo de solidaridad
				
				SELECT @SUELDOMES=SUM(D.VALOR)
					FROM dbo.TH_NOMINALIQD D
					JOIN dbo.TH_NOMINALIQC C on C.IDNOMINALIQC=D.IDNOMINALIQC
					WHERE D.IDHOJAVIDA=@IDHOJAVIDA AND D.IDCONCEPTO=29 AND C.MOD_ORIGEN='LIQNOM' AND MONTH(C.FECHALIQUIDACION)=@MES AND YEAR(C.FECHALIQUIDACION)=@ANIO

				IF (@SUELDOMES/@SALARIOMINIMOMES) >4.00
					BEGIN
						Set @IDCONCEPTO  =3
						Set @CODCONCEPTO  ='DD-APFSOLI'
						Set @VALOR_MOV=@SUELDOMES*0.01
						--LIQ D 
						INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV)
						VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250501','242518','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV) 
						SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_MOV,0)
					END

			END */
        --Cesantias 
			Set @IDCONCEPTO  =54
			Set @CODCONCEPTO  ='PV-CESANTI'
			Set @VALOR_MOV=(@TOTALDEVENGADOPERIODO*@POR_CESANTIAS)/100
			
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510124','250801','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

        --Int Cesantias 
			Set @IDCONCEPTO  =55
			Set @CODCONCEPTO  ='PV-INTCESA'
			Set @VALOR_MOV=(@VALOR_MOV*@INT_CESANTIAS)/100
			 
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510125','250802','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

		--Primas 
			Set @IDCONCEPTO  =56
			Set @CODCONCEPTO  ='PV-PRIMASE'
			Set @VALOR_MOV=(@TOTALDEVENGADOPERIODO*@POR_PRIMA)/100
			
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510152','250804','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

		--PV VACACIONES 
			Set @IDCONCEPTO  =57
			Set @CODCONCEPTO  ='PV-VACACIO'
			Set @VALOR_MOV=((@TOTALDEVENGADOPERIODO-@AUXTRANSPORTE)*@POR_VACACIONES)/100
			
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510117','250803','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

		--APORTES FONDOS DE PENSIONES EMPLEADOR 
			Set @IDCONCEPTO  =50
			Set @CODCONCEPTO  ='PV-APPENSI'
			Set @VALOR_MOV=((@TOTALDEVENGADOPERIODO-@AUXTRANSPORTE)*@POR_PENSIONES)/100
			
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510307','242518','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

		--Caja de compensacion 
			Set @IDCONCEPTO  =53
			Set @CODCONCEPTO  ='PV-CAJACOM'
			Set @VALOR_MOV=@VALOR_CCF
			SET @FORMULA='VALOR:( Salario:'+CONVERT(varchar,@SUELDOPERIODOPROVISIONES,23)+' *%:'+CONVERT(varchar,@POR_CAJA,10)+' /100 :'+STR(@VALOR_MOV);
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,FORMULAPLICAR,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510302','242520','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,@DIASPERIODO) 
		--PV  arl 
			Set @IDCONCEPTO  =52
			Set @CODCONCEPTO  ='PV-ARL'
			Set @VALOR_MOV=@VALOR_ARP
			SET @FORMULA='VALOR:( Salario:'+CONVERT(varchar,@SUELDOPERIODOPROVISIONES,23)+' *%:'+CONVERT(varchar,@POR_ARP,10)+' /100 :'+STR(@VALOR_MOV);
			--LIQ D 
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,FORMULAPLICAR,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510305','242532','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,@DIASPERIODO) 

		--Calcular neto
		SET @NETOPAGAR=( 
						(@SUELDOPERIODO+@AUXTRANSPORTE)
						-ISNULL((@VALOR_EPS_EMPLEADO+@VALOR_AFP_EMPLEADO),0) 
						-ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC=@IDNOMINA AND IDHOJAVIDA=@IDHOJAVIDA AND IDCONCEPTO IN(3)),0)
						-ISNULL((SELECT SUM(VALOR) FROM TH_NOMINALIQD WHERE IDNOMINALIQC=@IDNOMINA AND IDHOJAVIDA=@IDHOJAVIDA AND COD_NOVEDAD<>''),0)
						)
		--Crear cada registro base de empleados en base de nomina		
		INSERT INTO TH_NOMINA_BASE 
			(IDNOMINALIQC ,IDHOJAVIDA ,FECHALIQUIDACION ,DIAS_EPS,BASE_EPS,DIAS_AFP,BASE_AFP,DIAS_ARP,BASE_ARP,
			DIAS_CCF,BASE_CCF,DIAS_FONDO,BASE_FONDO,POR_FONDO,LIQUIDA,BAS_EPSSUP,BAS_PENSUP,MOD_ORIGEN,
			IDTIPOCOTIZANTE ,IDSUDTIPOCOTIZANTE,VALOR_SUBSIDIOTRANSPORTE,VALOR_AFP_EMPLEADOR,VALOR_AFP_EMPLEADO,
			VALOR_EPS_EMPLEADOR,VALOR_EPS_EMPLEADO,VALOR_ARP,VALOR_CCF,VALOR_SENA,VALOR_ICBF,
			VALOR_ESAP,VALOR_MINE,VALOR_FSOL,VALOR_FSUB,COD_DOCUME ,NUM_DOCUME ,DIA_EPSSLN,DIA_AFPSLN,BAS_EPSSLN,
			BAS_AFPSLN,VAL_EPSSLN,VAL_AFPSLN,POR_PENSLN,POR_PENEMP ,POR_ARP ,BAS_ARLSLN,BAS_CCFSLN,USUARIOTRCR ,FECHATRCR ,
			USUARIOTRED ,FECHATRED,SUELDO,IDCONTRATOHV)
		VALUES(@IDNOMINA,@IDHOJAVIDA,GETDATE(),@DIASPERIODO,@SUELDOPERIODO,@DIASPERIODO,@SUELDOPERIODO,@DIASPERIODO,@SUELDOPERIODO,
			@DIASPERIODO,@SUELDOPERIODO,0,0,0,0,0,0,'LIQNOM',1,0,@AUXTRANSPORTE,@VALOR_AFP_EMPLEADOR,@VALOR_AFP_EMPLEADO,
			@VALOR_EPS_EMPLEADOR,@VALOR_EPS_EMPLEADO,@VALOR_ARP,@VALOR_CCF,0,0,
			0,0,0,@NETOPAGAR,'','',0,0,0,
			0,0,0,@POR_PENSIONES,@POR_PENSIONEMPLEADO,@POR_ARP,0,0,@USERNAME,GETDATE(),@USERNAME,GETDATE(),@SALARIO,@IDCONTRATOHV
			)

			IF @DIASPERIODO > 14
			BEGIN
				EXECUTE dbo.sp_TH_NOVEDADESDESCUENTO @ANIO, @charMES, @DIAINICIAL,@DIAFINAL,@IDHOJAVIDA,@DIA,@IDNOMINA,@DIASPERIODO,@TOTALNOMINA OUTPUT
			END

END
