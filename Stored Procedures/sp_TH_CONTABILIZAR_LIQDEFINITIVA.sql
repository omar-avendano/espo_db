ALTER PROCEDURE [dbo].[sp_TH_CONTABILIZAR_LIQDEFINITIVA]
    @IDNOMINALIQC INT,
    @USERNAME VARCHAR(60),
    @OBSERVACIONES NVARCHAR(MAX),
    @MENSAJE VARCHAR(150) OUTPUT
AS
BEGIN
    SET NOCOUNT ON
    --Declarar variables a usar
    DECLARE 
        @IDHOJAVIDA INT =0,
        @IDCONTRATOHV INT =0,
        @CODTERCERO VARCHAR(15)=N'',
        @NUMASIENTO INT =0,
        @ESTADO CHAR(1)=''
    
    DECLARE
        @VALOR DECIMAL(10,2) =0,
        @VALORFONDOSPENSION DECIMAL(10,2) =0,
        @CUENTA VARCHAR(15)='',
        @CUENTADEBITO VARCHAR(15)='',
        @CUENTACREDITO VARCHAR(15)='',
        @CODIGOCONCEPTO VARCHAR(10)='',
        @CODIGOCENTRO VARCHAR(10)='',
        @CUENTABASE VARCHAR(5)='',
        @TIPO VARCHAR(1)=''

    IF @IDNOMINALIQC > 0
    BEGIN 
       
        DECLARE @FECHALIQUIDACION DATE

        SELECT @ESTADO=ESTADO,@FECHALIQUIDACION=FECHALIQUIDACION
        FROM TH_NOMINALIQC 
        WHERE IDNOMINALIQC=@IDNOMINALIQC

        IF LEN(@ESTADO)>0 AND @ESTADO='L'
            BEGIN  

                DECLARE 
                    @DVSUELDOB DECIMAL(10,2) =0,
                    @DVSUBTRAN DECIMAL(10,2) =0,
                    @PGCESANTI DECIMAL(10,2) =0,
                    @PGINTCESA DECIMAL(10,2) =0,
                    @PGVACACIO DECIMAL(10,2) =0,
                    @PGPRIMASE DECIMAL(10,2) =0,
                    @DDAUTEMPL     DECIMAL(10,2) = 0,
                    @DDLIBRANZ     DECIMAL(10,2) = 0,
                    @PGINDEMNI     DECIMAL(10,2) = 0,
                    @PVAPPENSI     DECIMAL(10,2) = 0,
                    @VALORSALUD_EMPLEADO DECIMAL(10,2) =0,
                    @VALORPENSION_EMPLEADO DECIMAL(10,2) =0
                
