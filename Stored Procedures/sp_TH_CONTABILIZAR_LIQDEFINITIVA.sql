                    END
                    --Pension Empleador Add
                    SET @NUMASIENTO=@NUMASIENTO+1;
                    SET @CUENTA = CASE 
                        WHEN @CUENTABASE = '7' THEN '750534' ELSE '510307' 
                    END;
                    SET @TIPO='D'
                    SET @VALOR=@PVAPPENSI
