                    @POR_PENSIONES real, 
                    @POR_PENSIONEMPLEADO real,
                    @POR_SALUD real, 
                    @POR_SALUDEMPLEADO real,
                    @POR_ARP real,
                    @POR_CAJA real,
                    @POR_PRIMA real,
                    @POR_CESANTIAS real,
                    @POR_INTCESANTIAS real,
                    @POR_VACACIONES real
                    
