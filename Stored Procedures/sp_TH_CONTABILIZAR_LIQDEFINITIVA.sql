                INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHALIQUIDACION)
                INNER JOIN TH_HV HV ON HV.IDHOJAVIDA = CHV.IDHOJAVIDA                
		        INNER JOIN dbo.TH_DM_CLASERIESGOARL CARL ON CARL.ANIO=YEAR(@FECHALIQUIDACION) AND CARL.CODIGO=CHV.CODIGORIESGOARL
                WHERE LIQ.IDNOMINALIQC = @IDNOMINALIQC

                IF @IDHOJAVIDA >0
                BEGIN
                    
                    --Recorrer valores liquidados
                    DECLARE CurLiquidaciones CURSOR FOR
                    SELECT LIQ.CODIGOCONCEPTO,SUM(LIQ.VALOR) AS VALOR ,LIQ.CUENTADEBITO,LIQ.CUENTACREDITO
                    FROM TH_NOMINALIQD LIQ
                    JOIN TH_PR_CONCEPTO C ON C.IDCONCEPTO = LIQ.IDCONCEPTO
                    JOIN TH_PR_MODOCONTABLE M ON M.COD_MODOCONTABLE = C.COD_MODOCONTABLE
                    WHERE LIQ.IDNOMINALIQC = @IDNOMINALIQC
                    GROUP BY LIQ.CODIGOCONCEPTO,LIQ.CUENTADEBITO,LIQ.CUENTACREDITO

                    OPEN CurLiquidaciones
                        FETCH NEXT FROM CurLiquidaciones INTO @CODIGOCONCEPTO,@VALOR,@CUENTADEBITO,@CUENTACREDITO

                        WHILE (@@FETCH_STATUS = 0) 
                        BEGIN

                            IF @CODIGOCONCEPTO = N'DV-SUELDOB'
                            BEGIN
                                SET @DVSUELDOB=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'DV-SUBTRAN'
                            BEGIN
                                SET @DVSUBTRAN=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'PG-CESANTI'
                            BEGIN
                                SET @PGCESANTI=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'PG-INTCESA'
                            BEGIN
                                SET @PGINTCESA=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'PG-PRIMASE'
                            BEGIN
                                SET @PGPRIMASE=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'PG-VACACIO'
                            BEGIN
                                SET @PGVACACIO=@VALOR
                            END
                            /* IF @CODIGOCONCEPTO = N'DD-AUTEMPL'
                            BEGIN
                                SET @DDAUTEMPL=@VALOR
                            END */
                            /* IF @CODIGOCONCEPTO = N'DD-LIBRANZ'
                            BEGIN
                                SET @DDLIBRANZ=@VALOR
                            END */
                            IF @CODIGOCONCEPTO = N'PG-INDEMNI'
                            BEGIN
                                SET @PGINDEMNI=@VALOR
                            END
                            IF @CODIGOCONCEPTO = N'PV-APPENSI'
                            BEGIN
                                SET @PVAPPENSI=@VALOR
                            END
                        
                            FETCH NEXT FROM CurLiquidaciones INTO @CODIGOCONCEPTO,@VALOR,@CUENTADEBITO,@CUENTACREDITO
                        END 

                        CLOSE CurLiquidaciones
                        DEALLOCATE CurLiquidaciones	

                    --SALARIO @CUENTABASE
                    SET @NUMASIENTO=@NUMASIENTO+1;
                    SET @CUENTA = CASE 
                        WHEN @CUENTABASE = '7' THEN '750501' ELSE '510101' 
                    END;
                    
