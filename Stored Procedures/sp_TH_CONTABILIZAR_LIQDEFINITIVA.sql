                    SET @TIPO='C'
                    SET @VALOR=(@DVSUELDOB*@POR_CAJA)/100
                    IF @VALOR>0
                    BEGIN
                        INSERT INTO TH_NOMINAMOVCNT (IDNOMINALIQC,NUMASIENTO,COD_TERCERO,CENTRO,TIPO_ASIENTO,COD_CUENTA,NATURALEZA,BASE,VALOR,CEN_SUB,FECHA_ENV,FECHA_LIQ,CONTABILIZADO,MOD_ORIGEN,FECHATRCR,USUARIOTRCR,FECHATRED,USUARIOTRED)
                        VALUES (@IDNOMINALIQC,@NUMASIENTO,@CODTERCERO,@CODIGOCENTRO,'L',@CUENTA,@TIPO,@VALOR,@VALOR,@CODIGOCENTRO,GETDATE(),GETDATE(),0,'LIQDEF',GETDATE(),@USERNAME,GETDATE(),@USERNAME)
