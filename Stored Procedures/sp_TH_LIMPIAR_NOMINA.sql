ALTER PROCEDURE [dbo].[sp_TH_LIMPIAR_NOMINA]
@IDNOMINA INT,
@USERNAME VARCHAR(60) 
AS
BEGIN
SET NOCOUNT ON

    IF EXISTS(SELECT 1 FROM dbo.TH_NOMINALIQC WHERE IDNOMINALIQC=@IDNOMINA AND (ESTADO='L' OR ESTADO='P') )
    BEGIN
            
        DELETE FROM TH_NOMINA_BASE where TH_NOMINA_BASE.IDNOMINALIQC=@IDNOMINA
        DELETE FROM TH_NOMINALIQD WHERE IDNOMINALIQC=@IDNOMINA

        --Cambiar de estado Nomina
        UPDATE TH_NOMINALIQC 
            SET ESTADO='P' 
        WHERE IDNOMINALIQC=@IDNOMINA 
  
    END 


END
