ALTER PROCEDURE [dbo].[sp_TH_LIQPRIMA]
@PERIODO INT,
@FECHALIQUIDACION DATETIME ,
@USERNAME VARCHAR(60) ,
@OBSERVACIONES NVARCHAR(MAX) ,
@MENSAJE varchar(150) OUTPUT
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE @IDLIQUIDACIONPRIMAC int    =0
    
	--Variables para recibir datos del cursor
	
    BEGIN
        IF NOT EXISTS (SELECT * FROM TH_NOMINALIQC 
                        WHERE PERIODO = @PERIODO AND MOD_ORIGEN='LIQPRI')
        BEGIN
            /* INSERT INTO TH_LIQUIDACIONPRIMAC (PERIODO, FECHA_LIQUIDACION, OBSERVACIONES,ESTADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
            VALUES (@PERIODO,@FECHALIQUIDACION,@OBSERVACIONES,'L',@USERNAME,@FECHALIQUIDACION,@USERNAME,@FECHALIQUIDACION) */

            INSERT INTO dbo.TH_NOMINALIQC (PERIODO, FECHALIQUIDACION, FECHAMOVIMIENTO, MOD_ORIGEN, ESTADO, DESCRIPCION, EMPLEADOS_LIQUIDADOS, OBSERVACIONESLIQUIDACION, USUARIOTRCR,FECHATRCR, USUARIOTRED, FECHATRED)
            VALUES (@PERIODO,@FECHALIQUIDACION,GETDATE(),'LIQPRI','L','LIQUIDACION PRIMA ',1,'LIQUIDACION PRIMA',@USERNAME,GETDATE(),@USERNAME,GETDATE())

            SET @IDLIQUIDACIONPRIMAC= SCOPE_IDENTITY()

            IF @IDLIQUIDACIONPRIMAC>0
                BEGIN
                    exec sp_TH_LIQPRIMA_DET @IDLIQUIDACIONPRIMAC,@PERIODO ,@USERNAME
                END
                

        END

        IF @IDLIQUIDACIONPRIMAC > 0
            BEGIN
                SET @MENSAJE='Registro agregado correctamente'
            END
        ELSE 
            BEGIN
                SET @MENSAJE='Registro ya existe' 
            END

    END

END
