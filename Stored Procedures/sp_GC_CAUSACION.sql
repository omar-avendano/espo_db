ALTER PROCEDURE [dbo].[sp_GC_CAUSACION]
(
  @PERIODO int
)
AS
BEGIN
SET NOCOUNT ON


	--Variables para recibir datos del cursor
	DECLARE @IDPREDIO int, @IDMOVGC int, @IDMOVGCANTERIOR int
	DECLARE @IDCICLO int, @NROASIENTO int
	DECLARE @CODDOCUME VARCHAR(10), @NUMDOCUME VARCHAR(30)  
	DECLARE @NUMFACTURA VARCHAR(50), @IDTERCERO VARCHAR(30), @IDCENTROCOSTO int, @CODCENTROCOSTO varchar(10)
	DECLARE @STRNROOBLIGACION VARCHAR(20), @NUMCUENTA varchar(30), @NOMCUENTA varchar(255), @BASERET decimal(18,2)

	DECLARE @IDCONCEPTO int, @CONCEPTO varchar(256), @NROOBLIGACION varchar(60), @VALOR decimal(18,2), @IDMOVCART int
	DECLARE @CREDITO decimal(18,2),@DEBITO decimal(18,2), @NATURALEZA char(1)
    DECLARE @TERCERO varchar(50), @FECHA date
	
	--SET @PERIODO = 202211
    SET @TERCERO = 'PROVEEDOR'
    SET @IDMOVGCANTERIOR = 0


    DELETE FROM GC_ASIENTO 
    WHERE FORMAT (FECHACR, 'yyyyMM') = @PERIODO
    AND TPDOC NOT IN (
        'CAUA',
        'CEG',
        'REC',
        'FAC',
        'AJU',
        'AOC',
        'NOM',
        'CIE'
    )

    UPDATE GC_MOV_C 
    SET  CONTABILIZADO = '0' 
    WHERE FORMAT (FECHA, 'yyyyMM') = @PERIODO
    AND CODDOCUME NOT IN (
        'CAUA',
        'CEG',
        'REC',
        'FAC',
        'AJU',
        'AOC',
        'NOM',
		'CIE'
		
    )



	--Recorrer personal que se va a incluir en la nomina
	DECLARE CurCausacion CURSOR FOR


    
 
    SELECT C.IDMOVGC, C.CODDOCUME, C.NUMDOCUME, 
	CASE WHEN C.CODDOCUMEREL='NOM' THEN CAST( D.IDTERCERO AS VARCHAR(20) ) ELSE CAST(P.NUMIDENTIFICACION AS VARCHAR(20) ) END AS NUMIDENTIFICACION, 
    D.IDCENTROCOSTO,  
    D.CODCENTROCOSTO, D.NUMCUENTA, D.NOMCUENTA, D.NATURALEZA, D.NROASIENTO, D.VALOR,
    C.FECHA, D.BASERET
    FROM GC_MOV_C C
    LEFT JOIN GC_MOV_D D ON C.IDMOVGC = D.IDMOVGC
    LEFT JOIN GC_PROVEEDOR P ON D.IDTERCERO = P.IDPROVEEDOR
    WHERE C.CONTABILIZADO = '0' AND C.INACTIVO = '0' 
    AND FORMAT (FECHA, 'yyyyMM') = @PERIODO


	OPEN CurCausacion
	FETCH NEXT FROM CurCausacion INTO  @IDMOVGC, @CODDOCUME, @NUMDOCUME, @IDTERCERO, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NOMCUENTA, @NATURALEZA, @NROASIENTO, @VALOR, @FECHA, @BASERET

	WHILE (@@FETCH_STATUS = 0) 
	BEGIN	

        IF( @IDMOVGCANTERIOR <> @IDMOVGC AND @IDMOVGCANTERIOR <> 0 ) BEGIN
             --actualizar causacion a contabilizado
            UPDATE GC_MOV_C SET CONTABILIZADO = 1 WHERE IDMOVGC = @IDMOVGCANTERIOR
        END

        SET @DEBITO = 0
        SET @CREDITO = 0

		--PRINT N'NATURALEZA:'+ @NATURALEZA +' VALOR:'+STR(@VALOR) + ' NOMCUENTA:' + @NOMCUENTA

        IF (@NATURALEZA = 'D') BEGIN
            SET @DEBITO = @VALOR
        END
        ELSE BEGIN
            SET @CREDITO = @VALOR
        END


        --insertar asientos
        INSERT INTO GC_ASIENTO (IDITEM, IDCENTROCOSTO, CODCENTROCOSTO, TERCERO, CODTERCERO, TPDOC, NUMDOC, FECHACR, NUMCTA, DEBITO, CREDITO, BASERET, USUARIOTRCR, FECHATRCR )
        VALUES ( @NROASIENTO, @IDCENTROCOSTO, @CODCENTROCOSTO, @TERCERO, @IDTERCERO, @CODDOCUME, @NUMDOCUME, @FECHA, @NUMCUENTA, @DEBITO, @CREDITO, @BASERET, 'SPASIENTO', GETDATE()  )


        SET @IDMOVGCANTERIOR = @IDMOVGC
       

		FETCH NEXT FROM CurCausacion INTO @IDMOVGC, @CODDOCUME, @NUMDOCUME, @IDTERCERO, @IDCENTROCOSTO, @CODCENTROCOSTO, @NUMCUENTA, @NOMCUENTA, @NATURALEZA, @NROASIENTO, @VALOR, @FECHA, @BASERET
	END 

	CLOSE CurCausacion
	DEALLOCATE CurCausacion	 
	
	
	UPDATE GC_MOV_C SET CONTABILIZADO = 1 
	WHERE CONTABILIZADO = '0' AND INACTIVO = '0' 
    AND FORMAT (FECHA, 'yyyyMM') = @PERIODO



    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '412' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '1'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '511' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '2'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '617' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '3'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '621' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '4'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '517' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '5'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '413' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '6'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '411' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '7'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '611' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '8'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '612' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '9'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '613' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '10'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '619' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '11'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '010' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '12'
    UPDATE GC_ASIENTO SET CODCENTROCOSTO = '513' WHERE  IDCENTROCOSTO > 0 AND CODCENTROCOSTO = 0  AND IDCENTROCOSTO = '13'


    UPDATE GC_ASIENTO SET TERCERO = 'NOMINA'  WHERE NUMCTA IN (
    '510101',
    '510123',
    '510124',
    '510125',
    '510117',
    '510152',
