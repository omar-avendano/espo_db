ALTER PROCEDURE [dbo].[sp_TH_LIQVACACIONES]
@IDHOJAVIDA INT,
@FECHA_INICIO DATE,
@FECHA_FINAL DATE,
@DIAS_SOLICITADOS INT,
@DIAS_PENDIENTES INT,
@FECHA_RETORNO DATE,
@FECHA_SOLICITUD DATE,
@FECHA_APROBACION DATE,
@USERNAME VARCHAR(60) ,
@OBSERVACIONES NVARCHAR(MAX),
@MENSAJE varchar(150) OUTPUT
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
    DECLARE @IDLIQUIDACIONVACACIONES INT    =0
    DECLARE 
    @NUMDIASREAL INT                        =0,
    @SALARIO decimal(10,2)		            =0,
    @NUMEROCONTRATO VARCHAR(50)		        =0,
    @VALOR_VACACIONES decimal(10,2)		    =0
   
    SET @MENSAJE=''

    IF @DIAS_SOLICITADOS>0 AND @DIAS_PENDIENTES>0
        BEGIN 
        --Traer datos de Empleado
        SELECT @SALARIO=CHV.SALARIO, @NUMEROCONTRATO=CHV.NUMEROCONTRATO
                FROM dbo.TH_HV HV
                INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
                INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.IDPARAMETROANUAL=CHV.IDPARAMETROANUAL
            WHERE HV.ESTADOHV=1 AND HV.IDHOJAVIDA=@IDHOJAVIDA

        --Calcular dias pendientes
        SET @DIAS_PENDIENTES=@DIAS_PENDIENTES-@DIAS_SOLICITADOS
        --Calcular dias reales sin fines de semana ni festivos
        SELECT @NUMDIASREAL=DATEDIFF(DAY, @FECHA_INICIO, DATEADD(day, 1, @FECHA_FINAL) )
        --Calcular valor de vacaciones
        SET @VALOR_VACACIONES=(@SALARIO/30)*@DIAS_SOLICITADOS     
    
        INSERT INTO TH_LIQUIDACIONVACACIONES
            (IDHOJAVIDA,FECHA_INICIO,FECHA_SOLICITUD,FECHA_FINAL,FECHA_RETORNO,FECHA_APROBACION,DIAS_SOLICITADOS,OBSERVACIONES,NUMEROCONTRATO,LIQUIDA,DIAS_APROBADOS,REMUNERACION,DIAS_PENDIENTES,DIAS_REAL,DEVENGADO,FECHA_DOCUMENTO,COD_DOCUMENTO,NUM_DOCUMENTO,HORA,CONTABILIZADO,ES_PAGA,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
        VALUES
            (@IDHOJAVIDA,@FECHA_INICIO,@FECHA_SOLICITUD,@FECHA_FINAL,@FECHA_RETORNO,@FECHA_APROBACION,@DIAS_SOLICITADOS,@OBSERVACIONES,@NUMEROCONTRATO,1,@DIAS_SOLICITADOS,@SALARIO,@DIAS_PENDIENTES,@NUMDIASREAL,@VALOR_VACACIONES,GETDATE(),'01','01',CONVERT (TIME, GETDATE()),0,0,@USERNAME,GETDATE(),@USERNAME,GETDATE())

        SET @IDLIQUIDACIONVACACIONES= SCOPE_IDENTITY()

    END


    IF @IDLIQUIDACIONVACACIONES > 0
            BEGIN
                SET @MENSAJE='Registro agregado correctamente'
            END
        ELSE 
            BEGIN
                SET @MENSAJE='Registro ya existe' 
            END

END
