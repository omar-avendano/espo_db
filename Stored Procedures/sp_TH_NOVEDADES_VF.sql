ALTER PROCEDURE [dbo].[sp_TH_NOVEDADES_VF]
    @FECHAINIPERIODO DATE,
    @FECHAFINPERIODO DATE,
    @IDHOJAVIDA INT,
    @SALARIO DECIMAL(10,2),
    @IDNOMINA INT,
    @SALARIOMINIMOMES DECIMAL(10,2),
    @DIASPERIODO INT OUTPUT,
    @SUBSIDIOTRANSPORTE DECIMAL(10,2),
    @SUELDOBASE DECIMAL(10,2) OUTPUT,
    @SUELDOPERIODOPROVISIONES DECIMAL(10,2) OUTPUT,
    @DIASBASEPROVISIONES INT OUTPUT,
    @SUBSIDIOTRANSPORTEBASE DECIMAL(10,2) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE 
        @SALARIODIA DECIMAL(10,2) = @SALARIO / 30,
        @SALARIODIAMINIMO DECIMAL(10,2) = @SALARIOMINIMOMES / 30,
        @VALOR_SUBTRADIA DECIMAL(10,6) = @SUBSIDIOTRANSPORTE / 30,
        @USERNAME VARCHAR(60) = 'ESPO',
		@CREARNUEVALIQUIDACION INT=0,
        @SUBSIDIOTRANSPORTEACUMULADO DECIMAL(10,2)=0,
        @DESCONTARSUBSIDIOTRANSPORTE DECIMAL(10,2)=0,
        @DESCONTARSUELDO DECIMAL(10,2)=0,
        @ANIO INT =YEAR(@FECHAINIPERIODO),
        @DIASPROVISIONES INT=0,
        @DIAS100 INT=0,
        @DIAS66 INT=0;
        
     DECLARE @VALORADD DECIMAL(10,2) = 0, @POR_PENSIONES REAL = 0;

    -- ===============================
    -- TABLA TEMPORAL PARA VARIACIONES
    -- ===============================
    CREATE TABLE #tblVariaciones (
        IDHOJAVIDA INT,
        FECHAINICIO DATE,
        FECHAFIN DATE,
        DIASNOVEDAD INT,
        SALARIOVARIACION DECIMAL(18,2),
        SALARIODIAVAR DECIMAL(18,2),
        SUELDOBASE DECIMAL(18,2),
        SUBSIDIOTRANSPORTEBASE DECIMAL(18,2)
    );

    -- Agrupar novedades
    SELECT 
        n.IDSUBTIPONOVEDAD,
        DIASNOVEDAD = SUM(IIF(n.FECHAFIN < @FECHAFINPERIODO, dbo.Days360(IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, n.FECHAFIN)), dbo.Days360(IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, @FECHAFINPERIODO)))),
        DIASNOVEDADCOMPLETAS = SUM(DATEDIFF(DAY, n.FECHAINICIO, DATEADD(DAY, 1, n.FECHAFIN))),
        DIASNOVEDAD2 = SUM(CASE WHEN IIF(n.FECHAFIN < @FECHAFINPERIODO, DATEDIFF(DAY, IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, n.FECHAFIN)), DATEDIFF(DAY, IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, @FECHAFINPERIODO))) >= 2 THEN 2 ELSE 1 END),--ELSE 0 LO CAMBIE PROVISIONAL
        DIASLABNOVEDAD = SUM(IIF(n.FECHAFIN < @FECHAFINPERIODO, dbo.GetDiasLaborales(IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), n.FECHAFIN), dbo.GetDiasLaborales(IIF(n.FECHAINICIO < @FECHAINIPERIODO, @FECHAINIPERIODO, n.FECHAINICIO), @FECHAFINPERIODO))),
        APLICA2 = SUM(IIF(n.FECHAINICIO < @FECHAINIPERIODO AND DATEDIFF(DAY, n.FECHAINICIO, @FECHAINIPERIODO) > 1, 0, 1)),
        NUMNOVEDADES = COUNT(*),
        VALORNOVEDAD = MAX(n.VALOR),
        PORC12 = MAX(stn.POR_1A2),
        PORC290 = MAX(stn.POR_3A90),
        PORC90YMAS = MAX(stn.POR_91_540),
        DAYSADDAPLICA2 = SUM(IIF(DATEDIFF(DAY, n.FECHAINICIO, @FECHAINIPERIODO) > 0, DATEDIFF(DAY, n.FECHAINICIO, @FECHAINIPERIODO), 0)),
        n.FECHAINICIO,n.FECHAFIN
    INTO #tmpNovedades
    FROM TH_NOVEDAD n
    LEFT JOIN TH_DM_SUBTIPONOVEDAD stn ON stn.IDSUBTIPONOVEDAD = n.IDSUBTIPONOVEDAD
    WHERE 
        n.FECHAINICIO <= @FECHAFINPERIODO 
        AND n.FECHAFIN >= @FECHAINIPERIODO
        AND n.IDHOJAVIDA = @IDHOJAVIDA
        AND n.ESTADO = 1
    GROUP BY n.IDSUBTIPONOVEDAD,n.FECHAINICIO,n.FECHAFIN;

    DECLARE 
        @IDSUBTIPONOVEDAD INT, @DIASNOVEDAD INT, @DIASNOVEDADCOMPLETAS INT,
        @DIASNOVEDAD2 INT, @DIASLABNOVEDAD INT, @APLICA2 INT, @NUMNOVEDADES INT;
    DECLARE @VALORNOVEDAD DECIMAL(10,2)=0;
    DECLARE @VALORNOVEDADACUMGEN DECIMAL(10,2)=0;
    DECLARE @PORC12 FLOAT;
    DECLARE @PORC290 FLOAT;
    DECLARE @PORC90YMAS FLOAT;
    DECLARE @DAYSADDAPLICA2 INT;
    DECLARE @VALORDIAINCAPACIDAD DECIMAL(10,2);
    DECLARE @DIASTRABAJADOS INT, @DIASNOVACUM INT=0, @DIASNOVACUMINGEN INT=0, @DIASTRABAJADOSSUBTRA INT=0;
    DECLARE @FECHAINICIO DATE, @FECHAFIN DATE;

    WHILE EXISTS (SELECT 1 FROM #tmpNovedades)
    BEGIN
        SELECT TOP 1
            @IDSUBTIPONOVEDAD = IDSUBTIPONOVEDAD,
            @DIASNOVEDAD = DIASNOVEDAD,
            @DIASNOVEDADCOMPLETAS = DIASNOVEDADCOMPLETAS,
            @DIASNOVEDAD2 = DIASNOVEDAD2,
            @DIASLABNOVEDAD = DIASLABNOVEDAD,
            @APLICA2 = APLICA2,
            @NUMNOVEDADES = NUMNOVEDADES,
            @VALORNOVEDAD = VALORNOVEDAD,
            @PORC12 = PORC12,
            @PORC290 = PORC290,
            @PORC90YMAS = PORC90YMAS,
            @DAYSADDAPLICA2 = DAYSADDAPLICA2,
            @FECHAINICIO=FECHAINICIO,
            @FECHAFIN=FECHAFIN
        FROM #tmpNovedades;

        -- ======================
        -- LÓGICA POR SUBTIPO
        -- ======================
        SET @DIASNOVACUM=@DIASNOVACUM+@DIASNOVEDAD;

        IF @IDSUBTIPONOVEDAD = 1 -- INCGEN
        BEGIN            
            --pRIMEROS DOS DIAS AL 100 SIN SUBSIDIO DE TRANSPORTE DE RESTO AL 66.66

            IF @IDHOJAVIDA =71
                BEGIN
                    SET @DIASNOVEDADCOMPLETAS = 91;
                END 


            IF @DIASNOVEDADCOMPLETAS > 90
                BEGIN
                    SET @VALORDIAINCAPACIDAD = (@SALARIODIA * @PORC90YMAS) / 100;
                END
            ELSE IF @DIASNOVEDADCOMPLETAS > 290
                BEGIN
                    SET @VALORDIAINCAPACIDAD = (@SALARIODIA * @PORC290) / 100;
                END 
            ELSE   
                BEGIN
                    SET @VALORDIAINCAPACIDAD = (@SALARIODIA * @PORC12) / 100;
                    PRINT 'VALOR INC 1:'+STR(@VALORDIAINCAPACIDAD);
                    IF @VALORDIAINCAPACIDAD < @SALARIODIAMINIMO SET @VALORDIAINCAPACIDAD = @SALARIODIAMINIMO;  
                    PRINT 'VALOR INC 2:'+STR(@VALORDIAINCAPACIDAD);
                END  

            IF @APLICA2 > 0 AND  @DIASNOVEDADCOMPLETAS <= 90
            BEGIN
                SET @DIAS66=(@DIASNOVEDAD -2);
                SET @VALORNOVEDADACUMGEN=@VALORNOVEDADACUMGEN+(@DIAS66*@VALORDIAINCAPACIDAD);
                SET @DIASNOVACUMINGEN=@DIASNOVACUMINGEN+@DIAS66;
                --PRINT 'DIAS 66:'+STR(@DIAS66);
                PRINT 'VALOR ACUM GEN:'+STR(@VALORNOVEDADACUMGEN);
                PRINT 'DIAS NOV ACUM ING GEN:'+STR(@DIASNOVACUMINGEN);
                --SET @DIAS100= @DIASPERIODO - @DIAS66;
            END
            ELSE
            BEGIN
                SET @DIAS66=@DIASNOVEDAD;
                SET @VALORNOVEDADACUMGEN=@VALORNOVEDADACUMGEN+(@DIAS66*@VALORDIAINCAPACIDAD);
                SET @DIASNOVACUMINGEN=@DIASNOVACUMINGEN+@DIAS66;
            END

            SET @DIAS100= @DIASPERIODO - @DIASNOVACUMINGEN;
            SET @SUELDOBASE = CEILING((@DIAS100 * @SALARIODIA) + @VALORNOVEDADACUMGEN);

            SET @DIASTRABAJADOS = @DIASPERIODO - @DIASNOVACUM;
            SET @DIASTRABAJADOSSUBTRA = @DIASPERIODO - @DIASNOVACUM; 
            
            SET @SUELDOPERIODOPROVISIONES = CEILING(@DIASTRABAJADOSSUBTRA * @SALARIODIA);
            --SET @SUELDOPERIODOPROVISIONES = @VALORNOVEDADACUMGEN;
            --SET @DIASBASEPROVISIONES = @DIASTRABAJADOS;
            SET @DIASBASEPROVISIONES =  @DIASNOVACUM;
            
            SET @SUBSIDIOTRANSPORTEBASE = CEILING(@VALOR_SUBTRADIA * @DIASTRABAJADOSSUBTRA);
            
            
        END
        ELSE IF @IDSUBTIPONOVEDAD = 2 -- INCPROF
        BEGIN
            --PRINT 'DIAS PERIODO:'+STR(@DIASPERIODO);
            --PRINT 'DIAS nov:'+STR(@DIASNOVEDAD);
            SET @VALORDIAINCAPACIDAD = @SALARIODIA;
            SET @DIASTRABAJADOS = @DIASPERIODO;            
            SET @DIASTRABAJADOSSUBTRA = @DIASPERIODO - @DIASNOVEDAD; 
            SET @SUELDOBASE = CEILING(@DIASTRABAJADOS * @SALARIODIA);
            SET @SUELDOPERIODOPROVISIONES = CEILING(@DIASTRABAJADOSSUBTRA * @VALORDIAINCAPACIDAD);
            --SET @DIASBASEPROVISIONES = @DIASNOVEDAD;
            SET @SUBSIDIOTRANSPORTEBASE = CEILING(@VALOR_SUBTRADIA * (@DIASPERIODO - @DIASNOVEDAD));
        END
        ELSE IF @IDSUBTIPONOVEDAD = 4 -- PATERNIDAD
        BEGIN
            SET @DIASTRABAJADOS = @DIASPERIODO;
            SET @SUELDOBASE = CEILING(@DIASTRABAJADOS * @SALARIODIA);
            SET @DIASBASEPROVISIONES = @DIASBASEPROVISIONES+@DIASNOVEDAD;
            SET @DIASTRABAJADOSSUBTRA = @DIASPERIODO - @DIASNOVEDAD;
            SET @SUELDOPERIODOPROVISIONES = CEILING(@DIASTRABAJADOSSUBTRA * @SALARIODIA);
            SET @SUBSIDIOTRANSPORTEBASE = CEILING(@VALOR_SUBTRADIA * @DIASTRABAJADOSSUBTRA);
            SET @DESCONTARSUBSIDIOTRANSPORTE=@VALOR_SUBTRADIA *@DIASNOVEDAD;
            SET @DIASPERIODO = @DIASTRABAJADOS;

			--PRINT 'AT 1:'+STR(@SUBSIDIOTRANSPORTEBASE)
        END
        ELSE IF @IDSUBTIPONOVEDAD = 6 -- NOREM
        BEGIN
            IF @SUELDOBASE>0 AND @DIASNOVACUM>@DIASNOVEDAD --Si viene el sueldo afectado por una novedad anterior
            BEGIN
                --Calculo de dias solo laborales 2025-09-02 Diyana SET @DIASTRABAJADOS = @DIASTRABAJADOS - CASE WHEN @DIASNOVEDAD < 7 THEN @DIASLABNOVEDAD ELSE @DIASNOVEDAD END;
                SET @DIASTRABAJADOS = @DIASTRABAJADOS - @DIASNOVEDAD;
                SET @SUELDOBASE = @SUELDOBASE - (CEILING(@DIASNOVEDAD * @SALARIODIA));                
                SET @DIASTRABAJADOSSUBTRA = @DIASTRABAJADOS;
               
            END
            ELSE
            BEGIN
                SET @DIASTRABAJADOS = @DIASPERIODO - @DIASNOVEDAD;
                --PRINT 'DIAS TRAB:'+STR( @DIASTRABAJADOS );
                SET @SUELDOBASE = CEILING(@DIASTRABAJADOS * @SALARIODIA);
                SET @DIASTRABAJADOSSUBTRA = @DIASTRABAJADOS;
            END
            
            SET @SUBSIDIOTRANSPORTEBASE = CEILING(@VALOR_SUBTRADIA * @DIASTRABAJADOSSUBTRA);
            SET @SUELDOPERIODOPROVISIONES = @DIASTRABAJADOS*@SALARIODIA;
            SET @DIASBASEPROVISIONES = @DIASBASEPROVISIONES+@DIASNOVEDAD;
            --PRINT 'DIAS TRAB 2:'+STR( @DIASTRABAJADOS );
            --PRINT 'DIAS pero 2:'+STR( @DIASPERIODO );
            --PRINT 'DIAS nov 2:'+STR( @DIASNOVEDAD );
            --PRINT 'SUELDO PROV:'+STR( @SUELDOPERIODOPROVISIONEs );
            --Calcular pension empleador por dias no remunerados
            IF @DIASTRABAJADOS > 0 AND @DIASTRABAJADOS < @DIASPERIODO
            BEGIN
                SELECT @POR_PENSIONES = POR_PENSIONES FROM TH_PARAMETROANUAL WHERE ANIO = TRY_CAST(@ANIO AS INT);
                IF @DIASNOVEDAD=0 SET @DIASNOVEDAD=CASE WHEN @DIASNOVEDAD < 7 THEN @DIASLABNOVEDAD ELSE @DIASNOVEDAD END;

                SET @VALORADD = ((@DIASNOVEDAD * @SALARIODIA) * @POR_PENSIONES) / 100;
                INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC, IDHOJAVIDA, IDCONCEPTO, CODIGOCONCEPTO, VALOR, FECHAMOVIMIENTO, FECHA_LIQUIDACION, USUARIO_PRELIQUIDO, CERRADO, CUENTADEBITO, CUENTACREDITO, CENTROCOSTO, FECHAPRELIQUIDACION, DOCUMENTO, IDCONTRATOHV, DIAS)
                VALUES (@IDNOMINA, @IDHOJAVIDA, 50, 'PV-APPENSI', @VALORADD, GETDATE(), GETDATE(), 'ESPO', 0, '510307', '242518', '123', GETDATE(), STR(@IDNOMINA), 0, @DIASTRABAJADOS);
            END
            ELSE IF @DIASNOVEDAD=@DIASPERIODO
            BEGIN
                SELECT @POR_PENSIONES = POR_PENSIONES FROM TH_PARAMETROANUAL WHERE ANIO = TRY_CAST(@ANIO AS INT);
                IF @DIASNOVEDAD=0 SET @DIASNOVEDAD=CASE WHEN @DIASNOVEDAD < 7 THEN @DIASLABNOVEDAD ELSE @DIASNOVEDAD END;

                SET @VALORADD = ((@DIASNOVEDAD * @SALARIODIA) * @POR_PENSIONES) / 100;
                INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC, IDHOJAVIDA, IDCONCEPTO, CODIGOCONCEPTO, VALOR, FECHAMOVIMIENTO, FECHA_LIQUIDACION, USUARIO_PRELIQUIDO, CERRADO, CUENTADEBITO, CUENTACREDITO, CENTROCOSTO, FECHAPRELIQUIDACION, DOCUMENTO, IDCONTRATOHV, DIAS)
                VALUES (@IDNOMINA, @IDHOJAVIDA, 50, 'PV-APPENSI', @VALORADD, GETDATE(), GETDATE(), 'ESPO', 0, '510307', '242518', '123', GETDATE(), STR(@IDNOMINA), 0, @DIASTRABAJADOS);

            END 

            SET @DIASPERIODO = @DIASTRABAJADOS;
        END
        ELSE IF @IDSUBTIPONOVEDAD = 7 -- SANCION
        BEGIN
           
            SET @DIASTRABAJADOS = @DIASPERIODO - @DIASNOVEDAD;
            SET @DIASBASEPROVISIONES = @DIASBASEPROVISIONES+@DIASNOVEDAD;
            SET @SUELDOBASE = CEILING(@DIASTRABAJADOS * @SALARIODIA);
            SET @SUBSIDIOTRANSPORTEBASE = CEILING(@VALOR_SUBTRADIA * @DIASTRABAJADOS);
            SET @SUELDOPERIODOPROVISIONES = @SUELDOBASE;
            SET @SUBSIDIOTRANSPORTEACUMULADO=@SUBSIDIOTRANSPORTEBASE;

            IF @DIASTRABAJADOS > 0 AND @DIASTRABAJADOS < @DIASPERIODO
            BEGIN
                SELECT @POR_PENSIONES = POR_PENSIONES FROM TH_PARAMETROANUAL WHERE ANIO = TRY_CAST(@ANIO AS INT);
                SET @VALORADD = ((@DIASNOVEDAD * @SALARIODIA) * @POR_PENSIONES) / 100;
                INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC, IDHOJAVIDA, IDCONCEPTO, CODIGOCONCEPTO, VALOR, FECHAMOVIMIENTO, FECHA_LIQUIDACION, USUARIO_PRELIQUIDO, CERRADO, CUENTADEBITO, CUENTACREDITO, CENTROCOSTO, FECHAPRELIQUIDACION, DOCUMENTO, IDCONTRATOHV, DIAS)
                VALUES (@IDNOMINA, @IDHOJAVIDA, 50, 'PV-APPENSI', @VALORADD, GETDATE(), GETDATE(), 'ESPO', 0, '510307', '242518', '123', GETDATE(), STR(@IDNOMINA), 0, @DIASTRABAJADOS);
            END
            SET @DIASPERIODO = @DIASTRABAJADOS;
        END
        ELSE IF @IDSUBTIPONOVEDAD = 8 -- VARIACIÓN SALARIO
        BEGIN
            DECLARE 
            @SALARIOVARIACION DECIMAL(10,2) = @VALORNOVEDAD,
            @SALARIODIAVAR DECIMAL(10,2) = @VALORNOVEDAD / 30;

            SET @DIASTRABAJADOS = @DIASPERIODO - @DIASNOVEDAD;
            
            SET @SUELDOBASE = CEILING(@DIASTRABAJADOS * @SALARIODIA);
            
            SET @SUBSIDIOTRANSPORTEACUMULADO = @SUBSIDIOTRANSPORTEACUMULADO+CEILING(@VALOR_SUBTRADIA * @DIASNOVEDAD)-@DESCONTARSUBSIDIOTRANSPORTE;
            SET @SUBSIDIOTRANSPORTEBASE=@SUBSIDIOTRANSPORTEACUMULADO;
            SET @DIASPERIODO = @DIASTRABAJADOS;

            SET @SUELDOPERIODOPROVISIONES = @SUELDOBASE;
			SET @CREARNUEVALIQUIDACION=1

            -- Insertar registro de variaciones tabla temporal
            INSERT INTO #tblVariaciones (IDHOJAVIDA, FECHAINICIO, FECHAFIN, DIASNOVEDAD, SALARIOVARIACION, SALARIODIAVAR, SUELDOBASE, SUBSIDIOTRANSPORTEBASE)
            VALUES (
                @IDHOJAVIDA,
                @FECHAINICIO,
                @FECHAFIN,
                @DIASNOVEDAD,
                @VALORNOVEDAD,
                @SALARIODIAVAR,
                CEILING(@DIASNOVEDAD * @SALARIODIAVAR),
                CEILING(@VALOR_SUBTRADIA * @DIASNOVEDAD)
            );

        END

        DELETE TOP (1) FROM #tmpNovedades;
    END

    DROP TABLE #tmpNovedades;

	IF @CREARNUEVALIQUIDACION=1
	BEGIN       

        IF EXISTS (SELECT 1 FROM #tblVariaciones)
        BEGIN
            DECLARE @IDHV INT, @FI DATE, @FF DATE, @DN INT, @SV DECIMAL(18,2),
                    @SVD DECIMAL(18,2), @SB DECIMAL(18,2), @ST DECIMAL(18,2);

            DECLARE curVar CURSOR FOR
                SELECT IDHOJAVIDA, FECHAINICIO, FECHAFIN, DIASNOVEDAD, SALARIOVARIACION, SALARIODIAVAR, SUELDOBASE, SUBSIDIOTRANSPORTEBASE
                FROM #tblVariaciones;

            OPEN curVar;
            FETCH NEXT FROM curVar INTO @IDHV, @FI, @FF, @DN, @SV, @SVD, @SB, @ST;

            WHILE @@FETCH_STATUS = 0
            BEGIN
                -- Aquí va tu INSERT de liquidación
                 IF @DIASPERIODO>0
                BEGIN
                    SET @SB=0;
                END 
                
                EXEC sp_TH_PRELIQUIDAR_NOMINA_HV
                    @IDNOMINA, @IDHV, @DN, @SV,@SB, @ST, @USERNAME;

               
                FETCH NEXT FROM curVar INTO @IDHV, @FI, @FF, @DN, @SV, @SVD, @SB, @ST;
            END

            CLOSE curVar;
            DEALLOCATE curVar;
        END

        SET @SUBSIDIOTRANSPORTEBASE=CEILING(@VALOR_SUBTRADIA * @DIASTRABAJADOS);
	END

END
