ALTER PROCEDURE [dbo].[sp_TH_LIQPRIMA_DET]
@IDLIQUIDACIONPRIMAC INT,
@PERIODO INT,
@USERNAME VARCHAR(60) 
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE 
    @TOTALDEVENGADOPERIODO decimal(12,2) 	=0,
    @FECHALIQUIDACION DATE					=NULL,
    @FECHAINICIOPERIODO DATE				=NULL,
    @FECHAINICIOPERIODOPADRE DATE				=NULL,
    @NUMMESESLIQUIDAR	INT 				=0,
    @NUMDIASLIQUIDAR	INT 				=0,
	@PROCESAR			BIT					=0,
	@NUMERO_EMPLEADOS	INT					=0,
	@ANIO	CHAR(4)					='',
	@MES	CHAR(2)					=''

	--Variables para recibir datos del cursor
	DECLARE @IDHOJAVIDA INT=0, 
	@IDCONTRATOPADRE INT =0,
	@CODIGOEMP varchar(15), 
	@SALARIO decimal(12,2),
	@SALARIOPADRE decimal(12,2),
	@FECHAINICIO date,
	@FECHAINICIOPADRE date,
	@APLICASUBTRAN BIT, 
	@SUBSIDIOTRANSPORTE decimal(12,2),
	@NUMEROCONTRATO VARCHAR(50),
    @PORCENTAJESALARIOBASE real
	--Variables a calcular por empleado
	DECLARE @VALOR_MOV decimal(12,2)		=0;
	DECLARE @VALOR_TOTAL decimal(12,2)		=0;
	DECLARE @SALARIOMINIMOMES decimal(12,2)		=0;
    DECLARE @DIASNOVEDAD int =0;
    --Extract the first 4 characters
    SET @ANIO=LEFT(CONVERT(varchar(6),@PERIODO), 4);
    SET @MES=RIGHT(CONVERT(varchar(6),@PERIODO), 2);
	SET @FECHALIQUIDACION=CAST(@ANIO+'-'+@MES+'-30' as date)
	IF @MES='06'
	BEGIN
		SET @FECHAINICIOPERIODO=CAST(@ANIO+'-01-01' as date)
	END
	ELSE IF @MES='12'
	BEGIN
		SET @FECHAINICIOPERIODO=CAST(@ANIO+'-07-01' as date)
	END
	--Recorrer personal activo para calculo de prima
  	DECLARE CurPersonal CURSOR FOR
	  SELECT HV.IDHOJAVIDA,HV.CODIGO,CHV.SALARIO,CHV.FECHAINICIO,IIF(CHV.SUBSIDIOTRANSPORTE=1, PA.SUBSIDIOTRANSPORTE, 0) AS SUBSIDIOTRANSPORTE,CHV.NUMEROCONTRATO,PA.SALARIOMINIMO,
	  ISNULL(PADRE.IDCONTRATOHV,0) AS IDCONTRATOPADRE,
	  ISNULL(PADRE.SALARIO,0) AS SALARIOPADRE,
	  PADRE.FECHAINICIO FECHAINICIOPADRE
		FROM  dbo.TH_CONTRATOHV CHV 
		INNER JOIN dbo.TH_HV HV ON CHV.IDHOJAVIDA = HV.IDHOJAVIDA 
		INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO = YEAR(@FECHALIQUIDACION)
		LEFT JOIN dbo.TH_CONTRATOHV PADRE ON PADRE.IDCONTRATOHV= CHV.IDCONTRATOHVPADRE AND (CHV.FECHAINICIO > @FECHAINICIOPERIODO AND CHV.FECHAINICIO <= @FECHALIQUIDACION)
		WHERE HV.ESTADOHV = 1 
		AND CHV.ESTADO = 1
		AND CHV.FECHAINICIO < @FECHALIQUIDACION
	  
	OPEN CurPersonal
	FETCH NEXT FROM CurPersonal INTO @IDHOJAVIDA, @CODIGOEMP, @SALARIO,@FECHAINICIO,@SUBSIDIOTRANSPORTE,@NUMEROCONTRATO,@SALARIOMINIMOMES,@IDCONTRATOPADRE,@SALARIOPADRE,@FECHAINICIOPADRE

	WHILE (@@FETCH_STATUS = 0) 
	BEGIN	

		SET @VALOR_MOV=0;

		IF @MES='06'
		BEGIN
			SET @FECHAINICIOPERIODO=CAST(@ANIO+'-01-01' as date)
		END
		ELSE IF @MES='12'
		BEGIN
			SET @FECHAINICIOPERIODO=CAST(@ANIO+'-07-01' as date)
		END

    	
		PRINT 'INI PERIODO:'
			PRINT @FECHAINICIOPERIODO

		PRINT 'HV:'+STR(@IDHOJAVIDA);
		PRINT 'INI PADRE:'
			PRINT @FECHAINICIOPADRE
		--Validar si hay contrato padre
		IF @IDCONTRATOPADRE>0
		BEGIN
			IF (@SALARIOPADRE/@SALARIOMINIMOMES) > 2.00 -- Quien gana mas de 2 sal min no se le suma el aux transporte
				BEGIN
					SET @TOTALDEVENGADOPERIODO = @SALARIOPADRE;
				END
			ELSE
				BEGIN
					SET @TOTALDEVENGADOPERIODO = @SALARIOPADRE+@SUBSIDIOTRANSPORTE;
				END
			
			--Validar inicio periodo para procesar registro
			
			IF @FECHAINICIOPADRE < @FECHAINICIOPERIODO
				BEGIN
					SET @PROCESAR=1
					SET @FECHAINICIOPERIODOPADRE=@FECHAINICIOPERIODO
				END
			ELSE IF @FECHAINICIOPADRE < DATEADD(day, 1, @FECHALIQUIDACION)
				BEGIN	
					SET @PROCESAR=1
					SET @FECHAINICIOPERIODOPADRE=@FECHAINICIOPADRE

				END
			ELSE
				BEGIN
					SET @PROCESAR=0
				END
			--Procesar Registros
			IF @PROCESAR =1
				BEGIN
					SET @DIASNOVEDAD=0;
					SET @NUMDIASLIQUIDAR=0;
					PRINT 'PADRE:'
					PRINT 'INI:'
					PRINT  @FECHAINICIOPERIODOPADRE
					PRINT 'FIN:'
					PRINT  @FECHAINICIO

					SELECT @NUMDIASLIQUIDAR=dbo.Days360( @FECHAINICIOPERIODOPADRE, @FECHAINICIO );
					PRINT 'DIAS:'+STR(@NUMDIASLIQUIDAR)
					
					--Revisar dias para descontar sanciones y dias no remunedados
					SELECT 
						@DIASNOVEDAD =  SUM(IIF(n.FECHAFIN < @FECHALIQUIDACION, dbo.Days360(IIF(n.FECHAINICIO < @FECHAINICIOPERIODOPADRE, @FECHAINICIOPERIODOPADRE, n.FECHAINICIO), DATEADD(DAY, 1, n.FECHAFIN)), dbo.Days360(IIF(n.FECHAINICIO < @FECHAINICIOPERIODOPADRE, @FECHAINICIOPERIODOPADRE, n.FECHAINICIO), DATEADD(DAY, 1, @FECHALIQUIDACION))))
					FROM TH_NOVEDAD n
					WHERE 
						n.FECHAINICIO <= @FECHALIQUIDACION 
						AND n.FECHAFIN >= @FECHAINICIOPERIODOPADRE
						AND n.IDHOJAVIDA = @IDHOJAVIDA
						AND n.IDSUBTIPONOVEDAD IN (6,7);

					IF @DIASNOVEDAD>0 SET @NUMDIASLIQUIDAR= @NUMDIASLIQUIDAR-@DIASNOVEDAD;
					
					--PRINT N'DEV: '+STR(@TOTALDEVENGADOPERIODO)+' DIAS:'+STR(@NUMDIASLIQUIDAR)
					SET @VALOR_MOV = CAST((@TOTALDEVENGADOPERIODO * @NUMDIASLIQUIDAR) / 360.0 AS decimal(12,2));
					
					INSERT INTO dbo.TH_LIQUIDACIONPRIMAD 
						(IDLIQUIDACIONPRIMAC,IDHOJAVIDA,NUMEROCONTRATO,FECHA_INICIOLIQUIDACION,FECHA_PRIMA,DIAS_PRIMA,BASE_PRIMA,VALOR_PRIMA,OBSERVACIONES,CONTABILIZADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
					VALUES 
						(@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,@NUMEROCONTRATO,@FECHAINICIOPERIODOPADRE,@FECHALIQUIDACION,@NUMDIASLIQUIDAR,@TOTALDEVENGADOPERIODO,@VALOR_MOV,'LIQ DETALLE',0,@USERNAME,GETDATE(),@USERNAME,GETDATE()) 
					
					SET @NUMERO_EMPLEADOS= @NUMERO_EMPLEADOS+1;
					SET @VALOR_TOTAL= @VALOR_TOTAL+@VALOR_MOV;

				END

		END

        IF (@SALARIO/@SALARIOMINIMOMES) > 2.00 -- Quien gana mas de 2 sal min no se le suma el aux transporte
		    BEGIN
                SET @TOTALDEVENGADOPERIODO = @SALARIO
            END
        ELSE
            BEGIN
                SET @TOTALDEVENGADOPERIODO = @SALARIO+@SUBSIDIOTRANSPORTE
            END
        
		--Validar inicio periodo para procesar registro
		IF @FECHAINICIO < @FECHAINICIOPERIODO
			BEGIN
				SET @PROCESAR=1
				SET @FECHAINICIOPERIODO=@FECHAINICIOPERIODO
			END
		ELSE IF @FECHAINICIO < DATEADD(day, 1, @FECHALIQUIDACION)
			BEGIN	
				SET @PROCESAR=1
				SET @FECHAINICIOPERIODO=@FECHAINICIO

			END
		ELSE
			BEGIN
				SET @PROCESAR=0
			END
        --Procesar Registros
		IF @PROCESAR =1
			BEGIN
                SET @DIASNOVEDAD=0;
				SET @NUMDIASLIQUIDAR=0;
				PRINT 'HIJO:'
				PRINT 'INI:'
				PRINT  @FECHAINICIOPERIODO
				PRINT 'FIN:'
				PRINT  @FECHALIQUIDACION
				SELECT @NUMDIASLIQUIDAR=dbo.Days360( @FECHAINICIOPERIODO, DATEADD(day, 1, @FECHALIQUIDACION) );
				PRINT 'DIAS:'+STR(@NUMDIASLIQUIDAR)
                --Revisar dias para descontar sanciones y dias no remunedados
                SELECT 
                    @DIASNOVEDAD =  SUM(IIF(n.FECHAFIN < @FECHALIQUIDACION, dbo.Days360(IIF(n.FECHAINICIO < @FECHAINICIOPERIODO, @FECHAINICIOPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, n.FECHAFIN)), dbo.Days360(IIF(n.FECHAINICIO < @FECHAINICIOPERIODO, @FECHAINICIOPERIODO, n.FECHAINICIO), DATEADD(DAY, 1, @FECHALIQUIDACION))))
                FROM TH_NOVEDAD n
                WHERE 
                    n.FECHAINICIO <= @FECHALIQUIDACION 
                    AND n.FECHAFIN >= @FECHAINICIOPERIODO
                    AND n.IDHOJAVIDA = @IDHOJAVIDA
                    AND n.IDSUBTIPONOVEDAD IN (6,7);

                IF @DIASNOVEDAD>0 SET @NUMDIASLIQUIDAR= @NUMDIASLIQUIDAR-@DIASNOVEDAD;

				
                --PRINT N'DEV: '+STR(@TOTALDEVENGADOPERIODO)+' DIAS:'+STR(@NUMDIASLIQUIDAR)
                SET @VALOR_MOV = CAST((@TOTALDEVENGADOPERIODO * @NUMDIASLIQUIDAR) / 360.0 AS decimal(12,2));
				
				INSERT INTO dbo.TH_LIQUIDACIONPRIMAD 
					(IDLIQUIDACIONPRIMAC,IDHOJAVIDA,NUMEROCONTRATO,FECHA_INICIOLIQUIDACION,FECHA_PRIMA,DIAS_PRIMA,BASE_PRIMA,VALOR_PRIMA,OBSERVACIONES,CONTABILIZADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
        		VALUES 
					(@IDLIQUIDACIONPRIMAC,@IDHOJAVIDA,@NUMEROCONTRATO,@FECHAINICIOPERIODO,@FECHALIQUIDACION,@NUMDIASLIQUIDAR,@TOTALDEVENGADOPERIODO,@VALOR_MOV,'LIQ DETALLE',0,@USERNAME,GETDATE(),@USERNAME,GETDATE()) 
				
				SET @NUMERO_EMPLEADOS= @NUMERO_EMPLEADOS+1;
				SET @VALOR_TOTAL= @VALOR_TOTAL+@VALOR_MOV;

			END
		
		FETCH NEXT FROM CurPersonal INTO @IDHOJAVIDA, @CODIGOEMP, @SALARIO,@FECHAINICIO,@SUBSIDIOTRANSPORTE,@NUMEROCONTRATO,@SALARIOMINIMOMES,@IDCONTRATOPADRE,@SALARIOPADRE,@FECHAINICIOPADRE
	END 

	CLOSE CurPersonal
	DEALLOCATE CurPersonal	 

	--Actualizar registro principal
	UPDATE TH_NOMINALIQC 
		SET 
			EMPLEADOS_LIQUIDADOS=@NUMERO_EMPLEADOS ,
			VALOR=@VALOR_TOTAL
	WHERE IDNOMINALIQC=@IDLIQUIDACIONPRIMAC

END
