			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS,CLASIFICACION)
