ALTER PROCEDURE [dbo].[sp_TH_PRENOM_REVVACACIONES]
@IDNOMINA INT,
@FECHAINICIOPERIODO DATE,
@FECHAFINPERIODO DATE,
@IDHOJAVIDA INT,
@SALARIO decimal(10,2),
@DIASPERIODO INT OUTPUT,
@SUBSIDIOTRANSPORTE decimal(10,2),
@SUELDOBASE decimal(10,2) OUTPUT,
@SUELDOPERIODOPROVISIONES decimal(10,2) OUTPUT,
@DIASBASEPROVISIONES INT OUTPUT,
@SUBSIDIOTRANSPORTEBASE decimal(10,2) OUTPUT
AS
BEGIN
	--PRINT 'ID HV : '+STR(@IDHOJAVIDA)+'FECHA INI: '+CONVERT(varchar,@FECHAINICIOPERIODO,23)+' FECHA FIN: '+CONVERT(varchar,@FECHAFINPERIODO,23)
	
    DECLARE @IDSUBTIPONOVEDAD int,@FECHAINICIO date, @FECHAFIN date ,
	@FORMULA NVARCHAR(250)='',
		@TOTALDIAS int,@TOTALDIASLABORALES int, @SALARIODIA decimal(10,2),    
		@DIASTRABAJADOS int, @ES_PAGA BIT=0,  @VALOR_MOV decimal(10,2),@IDCONTRATOHV INT =0,
		@FECHATRCR DATE = CAST(GETDATE() AS DATE), @DIASNOVEDADES INT=0;
	DECLARE @POR_PENSIONES REAL,
            @POR_SALUD REAL,
            @POR_INTCESANTIAS REAL,
			@POR_VACACIONES REAL,
			@POR_CESANTIAS REAL,
            @POR_PENSIONEMPLEADO REAL,
            @POR_SALUDEMPLEADO   REAL,
            @POR_CAJA   REAL,
            @POR_PRIMA   REAL,
            @INT_CESANTIAS   REAL;

	SELECT TOP 1 
		@IDCONTRATOHV = CHV.IDCONTRATOHV,
		@POR_PENSIONEMPLEADO = PA.POR_PENSIONEMPLEADO,
		@POR_SALUDEMPLEADO = PA.POR_SALUDEMPLEADO,
		@POR_PENSIONES=PA.POR_PENSIONES,
		@POR_SALUD=PA.POR_SALUD,
		@POR_CESANTIAS=PA.POR_CESANTIAS,
		@POR_VACACIONES=PA.POR_VACACIONES,
		@POR_INTCESANTIAS=PA.INT_CESANTIAS,
		@POR_PRIMA=PA.POR_PRIMA,
		@POR_CAJA=PA.POR_CAJA,
		@INT_CESANTIAS=PA.INT_CESANTIAS
	FROM  TH_HV HV 
	INNER JOIN dbo.TH_CONTRATOHV CHV ON HV.IDHOJAVIDA = CHV.IDHOJAVIDA AND CHV.ESTADO = 1
	INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO = YEAR(@FECHATRCR)
    WHERE HV.IDHOJAVIDA=@IDHOJAVIDA;
	
	--Cursor para recorrer novedades existentes	
	DECLARE CurVacaciones CURSOR FOR
		SELECT
		SUM(
		IIF(
			FECHA_FINAL < @FECHAFINPERIODO,
			dbo.Days360(IIF(FECHA_INICIO<@FECHAINICIOPERIODO,@FECHAINICIOPERIODO,FECHA_INICIO) ,FECHA_RETORNO),
			dbo.Days360(IIF(FECHA_INICIO<@FECHAINICIOPERIODO,@FECHAINICIOPERIODO,FECHA_INICIO) ,DATEADD(day, 1, @FECHAFINPERIODO))
			)
		) TOTALDIAS,
		SUM(
			IIF(
			FECHA_FINAL <@FECHAFINPERIODO,
			dbo.GetDiasLaborales(IIF(FECHA_INICIO<@FECHAINICIOPERIODO,@FECHAINICIOPERIODO,FECHA_INICIO),FECHA_RETORNO),
			dbo.GetDiasLaborales(IIF(FECHA_INICIO<@FECHAINICIOPERIODO,@FECHAINICIOPERIODO,FECHA_INICIO),@FECHAFINPERIODO)
			)
		) TOTALDIASLABORALES,
		MAX(FECHA_FINAL),
		MAX(CONVERT(int, ES_PAGA)) 
		FROM TH_LIQUIDACIONVACACIONES 
		WHERE (FECHA_INICIO<=@FECHAFINPERIODO AND FECHA_FINAL >= @FECHAINICIOPERIODO)
		AND IDHOJAVIDA=@IDHOJAVIDA  AND OBSERVACIONES <>'LIQ FINAL'
		GROUP BY IDHOJAVIDA
	
	OPEN CurVacaciones
	FETCH NEXT FROM CurVacaciones INTO @TOTALDIAS,@TOTALDIASLABORALES,@FECHAFIN,@ES_PAGA
	
	WHILE (@@FETCH_STATUS = 0) 
	BEGIN
		PRINT 'Dias periodo1: '+STR(@DIASPERIODO);
        Set @SALARIODIA=(@SALARIO/30);
		/* IF @FECHAFINPERIODO=EOMONTH(@FECHAINICIOPERIODO) AND MONTH(@FECHAFINPERIODO)=2
			BEGIN	
				IF @FECHAFIN > @FECHAFINPERIODO
					BEGIN
					print 'entro 1'
						SET @DIASPERIODO=@DIASPERIODO-(30-DAY(@FECHAFINPERIODO));
					END
			END */

		/* PRINT 'Total Dias: '+STR(@TOTALDIAS)+' Total Dias Laborales: '+STR(@TOTALDIASLABORALES)+' Es paga: '+STR(@ES_PAGA);
		PRINT 'Fecha fin: '+CONVERT(varchar,@FECHAFIN,23);
		PRINT 'salario dia : '+CONVERT(varchar,@SALARIODIA,23);
		PRINT 'Fecha inicio: '+CONVERT(varchar,@FECHAINICIOPERIODO,23);
		PRINT 'Fecha Fin periodo: '+CONVERT(varchar,@FECHAFINPERIODO,23);
		PRINT 'Dias periodo: '+STR(@DIASPERIODO); */
		--Guardar dias reportados de novedades en el periodo
		PRINT 'Dias periodo: '+STR(@DIASPERIODO);
		SET @DIASNOVEDADES=@DIASBASEPROVISIONES;
		PRINT 'Dias DIASNOVEDADES: '+STR(@DIASNOVEDADES);
		SET @DIASBASEPROVISIONES=@DIASPERIODO-@TOTALDIAS;
		IF @TOTALDIAS>0 AND @ES_PAGA=1
			BEGIN
        		SET @DIASBASEPROVISIONES=@DIASPERIODO-@TOTALDIAS;
			END 
		ELSE
			BEGIN
        		SET @DIASBASEPROVISIONES=@DIASPERIODO;
			END 

        --SET @DIASTRABAJADOS=@DIASPERIODO-@DIASNOVEDADES-@TOTALDIAS; -- ya viene acumulado de novedades los dias periodo
        SET @DIASTRABAJADOS=@DIASPERIODO-@TOTALDIAS;

        --SET @SUELDOBASE = CEILING(((@DIASTRABAJADOS)*@SALARIODIA))+@SUELDOPERIODOPROVISIONES;  -- se sumaba el residio proveniente de novedades , hay que evaluar mas casos
        SET @SUELDOBASE = CEILING(((@DIASTRABAJADOS)*@SALARIODIA));
        --SET @SUELDOPERIODOPROVISIONES= CEILING((@DIASTRABAJADOS)*@SALARIODIA)+@SUELDOPERIODOPROVISIONES;
        SET @SUELDOPERIODOPROVISIONES= CEILING((@DIASTRABAJADOS)*@SALARIODIA);
        SET @SUBSIDIOTRANSPORTEBASE = CEILING((@SUBSIDIOTRANSPORTE/30)*@DIASTRABAJADOS);
		SET @DIASPERIODO=@DIASTRABAJADOS;

		DECLARE @IDCONCEPTO INT=0;
		DECLARE @CODCONCEPTO VARCHAR(20)='';
		DECLARE @SALARIOPERIODO decimal(10,2)= @SALARIODIA*@TOTALDIAS;
		DECLARE @SUBSIDIOTRANSPORTEPREV decimal(10,2) =(@SUBSIDIOTRANSPORTE/30)*@TOTALDIAS;
		
		PRINT 'Dias trab: '+STR(@DIASTRABAJADOS);
		PRINT 'Dias prov: '+STR(@DIASBASEPROVISIONES);
		--Crear movimientos seguridad social cuando no entra en nomina por vacaciones
		IF @DIASTRABAJADOS=0 AND @TOTALDIAS > 14
		BEGIN
			
			--Salud
			SET @IDCONCEPTO  =5;
			SET @CODCONCEPTO  ='DD-APSALUD';
			SET @VALOR_MOV= (@SALARIOPERIODO*@POR_SALUDEMPLEADO)/100;
			--LIQ D 
			SET @FORMULA='VACAS VALOR:( Salario:'+STR(@SALARIOPERIODO)+' * % SALUD: '+STR(@POR_SALUDEMPLEADO)+' / 100 ) | Tot:'+STR(@VALOR_MOV);
			INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,FORMULAPLICAR,IDCONTRATOHV,DIAS)
			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250501','242519','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,@TOTALDIAS);
