			VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510117','250803','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,@DIASPERIODO) 

			
		END
		ELSE
		BEGIN

			--Salud
			SET @IDCONCEPTO  =75;
			SET @CODCONCEPTO  ='DD-APSALUD';
			SET @VALOR_MOV= (@SALARIOPERIODO*@POR_SALUDEMPLEADO)/100;
