ALTER PROCEDURE [dbo].[sp_TH_DIASNOVEDADESPERSONAL]
@IDHOJAVIDA INT,
@FECHAINICIO DATE,
@FECHAFIN DATE,
@OPCION VARCHAR(30) ,
@IDNOMINALIQC INT
AS
BEGIN
SET NOCOUNT ON
	--Variables 
	DECLARE @NUMDIASNOVEDADES INT=0;
	DECLARE @FECHAINICIONOV DATE =NULL;
	DECLARE @FECHAFINNOV DATE =NULL;
    DECLARE @IDSUBTIPONOVEDAD INT =0
	DECLARE @FECHAINICIO_CALCULODIAS DATE =NULL;
	DECLARE @FECHAFIN_CALCULODIAS DATE =NULL;
    DECLARE @SQLCURSOR NVARCHAR(4000)  ='';
    DECLARE @POR_PENSIONES REAL=0.00;
    DECLARE @VALORADD DECIMAL(10,2) = 0;
    DECLARE @SALARIO decimal(10,2)=0;
    DECLARE @DIASTRABAJADOS INT=0;
    DECLARE @SALARIODIA DECIMAL(10,2) = 0;

    SELECT @POR_PENSIONES = POR_PENSIONES FROM TH_PARAMETROANUAL WHERE ANIO =YEAR(@FECHAFIN);

    SELECT 
        @POR_PENSIONES=PA.POR_PENSIONES,
        @SALARIO=CHV.SALARIO
        FROM dbo.TH_HV HV
    INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
    INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHAFIN)
    WHERE  HV.IDHOJAVIDA=@IDHOJAVIDA 

    SET @SALARIODIA = @SALARIO / 30;

    /* SET @SQLCURSOR = 'DECLARE CurNovedadesPersonal CURSOR FOR 
                        SELECT FECHAINICIO,FECHAFIN
                        FROM TH_NOVEDAD
                        INNER JOIN TH_DM_SUBTIPONOVEDAD ON TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=TH_NOVEDAD.IDSUBTIPONOVEDAD
                        WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_DM_SUBTIPONOVEDAD.'+@OPCION+'=1
                        AND ( (FECHAINICIO BETWEEN @FECHAINICIO AND @FECHAFIN) 
                        OR (FECHAFIN BETWEEN @FECHAINICIO AND @FECHAFIN ) ) ' */
    SET @SQLCURSOR = 'DECLARE CurNovedadesPersonal CURSOR FOR 
                        SELECT TH_NOVEDAD.FECHAINICIO,TH_NOVEDAD.FECHAFIN,TH_NOVEDAD.IDSUBTIPONOVEDAD
                        FROM TH_NOVEDAD
                        INNER JOIN TH_DM_SUBTIPONOVEDAD ON TH_DM_SUBTIPONOVEDAD.IDSUBTIPONOVEDAD=TH_NOVEDAD.IDSUBTIPONOVEDAD
                        WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_DM_SUBTIPONOVEDAD.'+@OPCION+'=1
                        AND @FECHAINICIO < FECHAFIN
	                    AND @FECHAFIN > FECHAINICIO '

    EXECUTE sp_executesql @SQLCURSOR,
                        N'@IDHOJAVIDA INT,@FECHAINICIO DATE, @FECHAFIN DATE',
                        @IDHOJAVIDA,
                        @FECHAINICIO,
                        @FECHAFIN	     

	OPEN CurNovedadesPersonal
	FETCH NEXT FROM CurNovedadesPersonal INTO @FECHAINICIONOV,@FECHAFINNOV,@IDSUBTIPONOVEDAD

	WHILE (@@FETCH_STATUS = 0) 
	BEGIN	

        --Identificar fecha inicial para calcular dias
        IF @FECHAINICIONOV < @FECHAINICIO
            BEGIN
                SET @FECHAINICIO_CALCULODIAS=@FECHAINICIO
            END 
        ELSE
            BEGIN
                SET @FECHAINICIO_CALCULODIAS=@FECHAINICIONOV
            END 
        --Identificar fecha final para calcular dias
       
        IF @FECHAFINNOV > @FECHAFIN
            BEGIN
                SET @FECHAFIN_CALCULODIAS=@FECHAFIN
            END 
        ELSE
            BEGIN
                SET @FECHAFIN_CALCULODIAS=@FECHAFINNOV
            END 

		--Calcular diferencia de dias
        
        SET @NUMDIASNOVEDADES=@NUMDIASNOVEDADES+DATEDIFF(day, @FECHAINICIO_CALCULODIAS, DATEADD(day, 1, @FECHAFIN_CALCULODIAS) )
		
        IF @IDSUBTIPONOVEDAD = 6 -- NOREM
        BEGIN

            SET @VALORADD = ((@NUMDIASNOVEDADES * @SALARIODIA) * @POR_PENSIONES) / 100;
            IF @IDNOMINALIQC>0
            BEGIN
                IF NOT EXISTS (SELECT TOP 1 1 FROM dbo.TH_NOMINALIQD WHERE IDNOMINALIQC=@IDNOMINALIQC AND IDHOJAVIDA= @IDHOJAVIDA AND IDCONCEPTO=50 AND VALOR=@VALORADD AND DIAS=@NUMDIASNOVEDADES  )
                BEGIN
                    INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC, IDHOJAVIDA, IDCONCEPTO, CODIGOCONCEPTO, VALOR, FECHAMOVIMIENTO, FECHA_LIQUIDACION, USUARIO_PRELIQUIDO, CERRADO, CUENTADEBITO, CUENTACREDITO, CENTROCOSTO, FECHAPRELIQUIDACION, DOCUMENTO, IDCONTRATOHV, DIAS)
                    VALUES (@IDNOMINALIQC, @IDHOJAVIDA, 50, 'PV-APPENSI', @VALORADD, GETDATE(), GETDATE(), 'ESPO', 0, '510307', '242518', '123', GETDATE(), STR(@IDNOMINALIQC), 0, @NUMDIASNOVEDADES);
                END
            END

        END
        ELSE IF @IDSUBTIPONOVEDAD = 7 -- SANCION
        BEGIN           
            
            SET @VALORADD = ((@NUMDIASNOVEDADES * @SALARIODIA) * @POR_PENSIONES) / 100;
            IF @IDNOMINALIQC>0
            BEGIN
                IF NOT EXISTS (SELECT TOP 1 1 FROM dbo.TH_NOMINALIQD WHERE IDNOMINALIQC=@IDNOMINALIQC AND IDHOJAVIDA= @IDHOJAVIDA AND IDCONCEPTO=50 AND VALOR=@VALORADD AND DIAS=@NUMDIASNOVEDADES  )
                BEGIN
                    INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC, IDHOJAVIDA, IDCONCEPTO, CODIGOCONCEPTO, VALOR, FECHAMOVIMIENTO, FECHA_LIQUIDACION, USUARIO_PRELIQUIDO, CERRADO, CUENTADEBITO, CUENTACREDITO, CENTROCOSTO, FECHAPRELIQUIDACION, DOCUMENTO, IDCONTRATOHV, DIAS)
                    VALUES (@IDNOMINALIQC, @IDHOJAVIDA, 50, 'PV-APPENSI', @VALORADD, GETDATE(), GETDATE(), 'ESPO', 0, '510307', '242518', '123', GETDATE(), STR(@IDNOMINALIQC), 0, @NUMDIASNOVEDADES);
                END
            END
        END
        
        FETCH NEXT FROM CurNovedadesPersonal INTO @FECHAINICIONOV,@FECHAFINNOV,@IDSUBTIPONOVEDAD
	END 

	CLOSE CurNovedadesPersonal
	DEALLOCATE CurNovedadesPersonal	  

    RETURN @NUMDIASNOVEDADES

END
