ALTER PROCEDURE [dbo].[sp_TH_LIQCESANTIAS_DET]
@IDLIQUIDACIONCESANTIASC INT,
@PERIODO INT,
@USERNAME VARCHAR(60) ,
@IDHOJAVIDALIQ INT =NULL,
@FECHARETIRO DATE =NULL
AS
BEGIN
SET NOCOUNT ON
	--Variables Periodo
	DECLARE 
    @TOTALDEVENGADOPERIODO decimal(10,2) 	=0,
    @FECHALIQUIDACION DATE					=NULL,
    @FECHAINICIOPERIODO DATE				=NULL,
    @FECHAULTIMALIQUIDACION DATE			=NULL,
    @NUMMESESLIQUIDAR	INT 				=0,
    @NUMDIASLIQUIDAR	INT 				=0,
    @NUMDIASNOVEDADES	INT 				=0,
	@PROCESAR			BIT					=0,
	@NUMERO_EMPLEADOS	INT					=0,
	@FORMULA NVARCHAR(250)=''
	--Variables para recibir datos del cursor
	DECLARE @IDHOJAVIDA INT, @CODIGOEMP varchar(15), @SALARIO decimal(10,2),@FECHAINICIO date,@APLICASUBTRAN BIT, @SUBSIDIOTRANSPORTE decimal(10,2),@NUMEROCONTRATO VARCHAR(50)
	--Variables a calcular por empleado
	DECLARE @VALOR_MOV decimal(10,2)		=0
	DECLARE @VALOR_TOTAL decimal(18,2)		=0

	--Recorrer personal que se va a incluir en la nomina
	IF @IDHOJAVIDALIQ IS NULL
		BEGIN
			DECLARE CurPersonal CURSOR FOR
			SELECT HV.IDHOJAVIDA,HV.CODIGO,CHV.SALARIO,CHV.FECHAINICIO,IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0) AS SUBSIDIOTRANSPORTE,CHV.NUMEROCONTRATO
				FROM dbo.TH_HV HV
				INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
				JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=@PERIODO
			WHERE HV.ESTADOHV=1 --AND CHV.FECHAVENCIMIENTO > GETDATE()
		END
	ELSE IF @IDHOJAVIDALIQ>0
		BEGIN

			DECLARE CurPersonal CURSOR FOR
				SELECT HV.IDHOJAVIDA,HV.CODIGO,MAX(CHV.SALARIO),
	                MIN(CHV.FECHAINICIO),--MAX(CHV.FECHAVENCIMIENTO),
	                MAX(IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0)) AS SUBSIDIOTRANSPORTE,
					MAX(CHV.NUMEROCONTRATO)
	                    FROM dbo.TH_HV HV
	                    --INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA 
	                    --JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=@PERIODO
						INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
						INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHARETIRO)
	                WHERE HV.IDHOJAVIDA=@IDHOJAVIDALIQ 
	               /*  AND 
	                (
	                	(CAST(str(@PERIODO)+'-01-01' as date) between CHV.FECHAINICIO and CHV.FECHAVENCIMIENTO
	                		OR CAST(str(@PERIODO)+'-12-31' as date)  between CHV.FECHAINICIO and CHV.FECHAVENCIMIENTO )
						OR 
						(CAST(str(@PERIODO)+'-01-01' as date) <= CHV.FECHAINICIO AND CHV.FECHAVENCIMIENTO <= CAST(str(@PERIODO)+'-12-31' as date)  )
	                ) */	                
				GROUP BY CASE WHEN CHV.IDCONTRATOHVPADRE >0 THEN CHV.IDCONTRATOHVPADRE ELSE CHV.IDCONTRATOHV END,
				HV.IDHOJAVIDA,HV.CODIGO,(PA.SALARIOMINIMO*CHV.PORCENTAJESALARIOBASE)
				HAVING SUM(CHV.ESTADO)>0

			/* SELECT HV.IDHOJAVIDA,HV.CODIGO,(PA.SALARIOMINIMO*CHV.PORCENTAJESALARIOBASE),CHV.FECHAINICIO,IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0) AS SUBSIDIOTRANSPORTE,CHV.NUMEROCONTRATO
				FROM dbo.TH_HV HV
				INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
				JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=@PERIODO
			WHERE HV.ESTADOHV=1 AND HV.IDHOJAVIDA=@IDHOJAVIDALIQ	 */
		END 

	OPEN CurPersonal
	FETCH NEXT FROM CurPersonal INTO @IDHOJAVIDA, @CODIGOEMP, @SALARIO,@FECHAINICIO,@SUBSIDIOTRANSPORTE,@NUMEROCONTRATO

	WHILE (@@FETCH_STATUS = 0) 
	BEGIN	
		SET @FECHALIQUIDACION=CAST(str(@PERIODO)+'-12-31' as date)
		SET @FECHAINICIOPERIODO=NULL
		SET @FECHAULTIMALIQUIDACION=NULL
		SET @VALOR_MOV=0
		SET @TOTALDEVENGADOPERIODO = @SALARIO+@SUBSIDIOTRANSPORTE
       
		--Traer ultima liquidacion
		SELECT TOP 1 @FECHAULTIMALIQUIDACION=FECHA_CESANTIAS
		FROM TH_LIQUIDACIONCESANTIASD
		WHERE IDHOJAVIDA=@IDHOJAVIDA ORDER BY IDLIQUIDACIONCESANTIASD DESC

		IF @FECHAULTIMALIQUIDACION IS NOT NULL
			BEGIN
				--Validar si la ultima liquidacion es menor a la fecha de corte del periodo seleccionado
				 
				IF @FECHAULTIMALIQUIDACION < CAST(str(@PERIODO)+'-12-31' as date) 
					BEGIN
						SET @PROCESAR=1
						IF @FECHAINICIO > @FECHAULTIMALIQUIDACION AND @FECHAINICIO < CAST(str(@PERIODO)+'-12-31' as date)
							BEGIN
								SET @FECHAINICIOPERIODO=@FECHAINICIO
							END 
						ELSE
							BEGIN
								SET @FECHAINICIOPERIODO=DATEADD(day, 1, @FECHAULTIMALIQUIDACION)
							END
					END 
				ELSE
					BEGIN
						SET @PROCESAR=0
					END 
			END
		ELSE
			BEGIN
				--Validar inicio periodo para procesar registro
				IF @FECHAINICIO <= CAST(str(@PERIODO)+'-01-01' as date)
					BEGIN
						SET @PROCESAR=1
						SET @FECHAINICIOPERIODO=CAST(str(@PERIODO)+'-01-01' as date)
					END
				ELSE IF @FECHAINICIO < DATEADD(day, 1, @FECHALIQUIDACION)
					BEGIN	
						SET @PROCESAR=1
						SET @FECHAINICIOPERIODO=@FECHAINICIO
						
						-- Revisar si tiene contratos anteriores del mismo periodo
						-- Enviar id hojavida , contrato , periodo
						EXEC sp_TH_LIQCESANTIAS_CONTANTE @IDLIQUIDACIONCESANTIASC,@PERIODO,@NUMEROCONTRATO,@USERNAME,@IDHOJAVIDALIQ ,@FECHAINICIOPERIODO,@TOTALDEVENGADOPERIODO

					END
				ELSE
					BEGIN
						--Verificar si se tiene un contrato anterior de ese año
						SELECT TOP 1 @FECHAINICIOPERIODO=TH_CONTRATOHV.FECHAINICIO,@NUMEROCONTRATO=TH_CONTRATOHV.NUMEROCONTRATO,
                            @SALARIO=(TH_CONTRATOHV.SALARIO),
                            @SUBSIDIOTRANSPORTE=IIF(TH_CONTRATOHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0)
						FROM TH_CONTRATOHV
						JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=@PERIODO
						WHERE IDHOJAVIDA=@IDHOJAVIDA AND TH_CONTRATOHV.ESTADO=0 AND YEAR(TH_CONTRATOHV.FECHAINICIO)=@PERIODO
						ORDER BY TH_CONTRATOHV.IDCONTRATOHV DESC

						IF @FECHAINICIOPERIODO IS NOT NULL
							BEGIN
								SET @PROCESAR=1
								SET @TOTALDEVENGADOPERIODO = @SALARIO+@SUBSIDIOTRANSPORTE
							END
						ELSE
							BEGIN
								SET @PROCESAR=0
							END
					END
			END 
		
		--Procesar registros con fecha inicio identificada en la validacion anterior
		IF @PROCESAR =1
			BEGIN
				IF @IDHOJAVIDALIQ>0 
					BEGIN
						SET @FECHALIQUIDACION= @FECHARETIRO
					END
				--Traer dias de novedades que afectan cesantias
				
				EXEC @NUMDIASNOVEDADES=sp_TH_DIASNOVEDADESPERSONAL @IDHOJAVIDA,@FECHAINICIOPERIODO ,@FECHALIQUIDACION,'AFECTA_CESANTIAS', @IDLIQUIDACIONCESANTIASC;
				--Dias a liquidar cesantias segun periodo de trabajo
				
				SELECT @NUMDIASLIQUIDAR=dbo.Days360( @FECHAINICIOPERIODO, DATEADD(day, 1, @FECHALIQUIDACION) )
				
				--Descontar dias de novedades si hay
				IF @NUMDIASNOVEDADES>0
					BEGIN
						SET @NUMDIASLIQUIDAR=@NUMDIASLIQUIDAR-@NUMDIASNOVEDADES
					END
				--Calcular valor de liquidacion
				SET @FORMULA='FINI:'+CONVERT(varchar,@FECHAINICIOPERIODO,23)+' FFIN:'+CONVERT(varchar,@FECHALIQUIDACION,23)+' TOTDEV:'+STR(@TOTALDEVENGADOPERIODO)+' * DIAS: '+STR(@NUMDIASLIQUIDAR)+' / 360  | DIAS NOV:'+STR(@NUMDIASNOVEDADES)
				SET @VALOR_MOV= (@TOTALDEVENGADOPERIODO*@NUMDIASLIQUIDAR)/360
				--Guardar registro
				INSERT INTO dbo.TH_LIQUIDACIONCESANTIASD 
					(IDLIQUIDACIONCESANTIASC,IDHOJAVIDA,NUMEROCONTRATO,FECHA_INICIOLIQUIDACION,FECHA_CESANTIAS,DIAS_CESANTIAS,BASE_CESANTIAS,VALOR_CESANTIAS,OBSERVACIONES,CONTABILIZADO,USUARIOTRCR,FECHATRCR,USUARIOTRED,FECHATRED)
        		VALUES 
					(@IDLIQUIDACIONCESANTIASC,@IDHOJAVIDA,@NUMEROCONTRATO,@FECHAINICIOPERIODO,@FECHALIQUIDACION,@NUMDIASLIQUIDAR,@TOTALDEVENGADOPERIODO,@VALOR_MOV,'LIQ CESANTIAS COD: '+@CODIGOEMP,0,@USERNAME,GETDATE(),@USERNAME,GETDATE())  
				
				--LIQ D 
				INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,FORMULAPLICAR)
				VALUES (@IDLIQUIDACIONCESANTIASC,@IDHOJAVIDA,41,'PG-CESANTI',@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'250801','250502','123',GETDATE(),@FORMULA) 

				SET @NUMERO_EMPLEADOS= @NUMERO_EMPLEADOS+1

				SET @VALOR_TOTAL=@VALOR_TOTAL +@VALOR_MOV

			END 
			
		FETCH NEXT FROM CurPersonal INTO @IDHOJAVIDA, @CODIGOEMP, @SALARIO,@FECHAINICIO,@SUBSIDIOTRANSPORTE,@NUMEROCONTRATO
	END 

	CLOSE CurPersonal
	DEALLOCATE CurPersonal	 

	--Insertar linea en cero por si desean incluir otro valor de cesantias
    --LIQ D 
	INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,FORMULAPLICAR)
	VALUES (@IDLIQUIDACIONCESANTIASC,@IDHOJAVIDALIQ,41,'PG-CESANTI',0,GETDATE(),GETDATE(),'ESPO',0,'250801','250502','123',GETDATE(),'') 
	
	--Actualizar registro principal	
	IF @NUMERO_EMPLEADOS >1
		BEGIN
			UPDATE TH_NOMINALIQC 
				SET 
					EMPLEADOS_LIQUIDADOS=@NUMERO_EMPLEADOS ,
					VALOR=@VALOR_TOTAL
			WHERE IDNOMINALIQC=@IDLIQUIDACIONCESANTIASC
		END

END
GO