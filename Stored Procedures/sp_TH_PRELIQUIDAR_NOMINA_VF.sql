CREATE PROCEDURE [dbo].[sp_TH_PRELIQUIDAR_NOMINA_VF]
@IDNOMINA INT,
@USERNAME VARCHAR(60) ,
@MENSAJE NVARCHAR(MAX) OUTPUT
AS
BEGIN 
SET NOCOUNT ON
	--Variables Periodo
	SET @MENSAJE='Proceso ejecutado correctamente';
	DECLARE @IDTIPONOMINA INT,
	@DIASPERIODO INT,
	@DIASPERIODOBASE INT,
    @SUELDOPERIODO decimal(10,2), 
    @NETOPAGAR decimal(10,2), 
    @SUELDOMES decimal(10,2)=0, 
    @SALARIOMINIMOMES decimal(10,2), 
    @SUELDOPERIODOPROVISIONES decimal(10,2)=0, 
    @AUXTRANSPORTEPERIODO decimal(10,2)	=0 ,
    @AUXTRANSPORTEBASE decimal(10,2)	=0 ,
    @SALUDPERIODO decimal(10,2) ,
    @PENSIONPERIODO decimal(10,2) ,
    @TOTALDEVENGADOPERIODO decimal(10,2) ,
    @TOTALDEVENGADOPERIODOAPORTES decimal(10,2) ,
    @TOTALSALARIOPAGARPERIODO decimal(10,2) ,
    @TOTALNOMINA decimal(12,2) =0,
    @TOTNOM decimal(12,2) =0,
    @TOTNOM_DESC decimal(12,2) =0,
    @FECHAINICIO DATE ,
    @FECHAINICIOPERIODO DATE ,
    @FECHAFINPERIODO DATE ,
    @FECHAINICIOPERIODOHV DATE ,
    @FECHAFINPERIODOHV DATE ,
    @ANIO int, 
	@MES int, 
    @DIA int,
	@DIAINICIAL char(2),
    @DIAFINAL char(2),
    @DIASBASEPROVISIONES int,
    @DIASVACASSOLIDARIDAD int=0,
    @NUM_EMPLEADOS int =0,
	@FORMULA NVARCHAR(250)='',
	@FLAGDOSPAGOS INT=0,
	@CLASIFICACION VARCHAR(3)='',
	@FECHAINICIOMES DATE,
	@CUENTASOLIDARIDAD VARCHAR(15)='250501';

	--Variables para recibir datos del cursor
	DECLARE @IDHOJAVIDA int, 
			@IDCONTRATOHV int,
			@CODIGOEMP varchar(15), 
			@SALARIO decimal(10,2),
			@APLICASUBTRAN BIT, 
			@SUBSIDIOTRANSPORTE decimal(10,2) =0, 
			@POR_PENSIONES real, 
			@POR_PENSIONEMPLEADO real,
			@POR_SALUD real, 
			@POR_SALUDEMPLEADO real,
			@POR_ARP real,
			@POR_CAJA real,
			@POR_CESANTIAS real,
			@PORCENTAJESALARIOBASE real,
			@POR_PRIMA real,@INT_CESANTIAS real, @POR_VACACIONES real
	--Variables a calcular por empleado
	DECLARE @VALOR_AFP_EMPLEADOR decimal(10,2)		=0,
			@VALOR_AFP_EMPLEADO decimal(10,2)		=0,
			@VALOR_AFP_EMPLEADOEXCESO decimal(10,2)	=0,
			@VALOR_AFP_EMPLEADOREXCESO decimal(10,2)=0,
			@VALOR_CCF_EMPLEADOREXCESO decimal(10,2)=0,
			@VALOR_SUBSIDIOTRANSPORTE decimal(10,2)	=0,
			@VALOR_EPS_EMPLEADOR decimal(10,2)		=0,
			@VALOR_EPS_EMPLEADO decimal(10,2)		=0,
			@VALOR_EPS_EMPLEADOEXCESO decimal(10,2)	=0,
			@VALOR_ARP decimal(10,2)				=0,
			@VALOR_CCF decimal(10,2)				=0,
			@VALOR_MOV decimal(10,2)				=0

	-- Limpiar antes de correr
	EXECUTE sp_TH_LIMPIAR_NOMINA @IDNOMINA,@USERNAME

	--Traer datos iniciales de nomina
	SELECT 
		@ANIO=YEAR(FECHALIQUIDACION) ,@MES=MONTH(FECHALIQUIDACION) ,@DIA=DAY(FECHALIQUIDACION),
		@IDTIPONOMINA=IDTIPONOMINA,@DIAFINAL=DAY(EOMONTH(FECHALIQUIDACION)),
	    -- Fecha inicio
	    @FECHAINICIOPERIODO=CASE 
	        -- 🟢 QUINCENAL
	        WHEN IDTIPONOMINA = 1 THEN 
	            CASE 
	                WHEN DAY(fechaliquidacion) = 15 THEN 
	                    DATEFROMPARTS(YEAR(fechaliquidacion), MONTH(fechaliquidacion), 1)
	                ELSE 
	                    DATEFROMPARTS(YEAR(fechaliquidacion), MONTH(fechaliquidacion), 16)
	            END
	        -- 🔵 MENSUAL
	        WHEN IDTIPONOMINA = 2 THEN 
	            DATEFROMPARTS(YEAR(fechaliquidacion), MONTH(fechaliquidacion), 1)
	    END,
	    -- Fecha fin
	    @FECHAFINPERIODO=CASE 
	        -- 🟢 QUINCENAL
	        WHEN IDTIPONOMINA = 1 THEN 
	            CASE 
	                -- Primera quincena
	                WHEN DAY(fechaliquidacion) = 15 THEN 
	                    DATEFROMPARTS(YEAR(fechaliquidacion), MONTH(fechaliquidacion), 15)
	                -- Segunda quincena
	                ELSE 
	                    CASE 
	                        WHEN MONTH(fechaliquidacion) = 2 THEN 
	                            EOMONTH(fechaliquidacion)
	                        ELSE 
	                            DATEFROMPARTS(YEAR(fechaliquidacion),MONTH(fechaliquidacion),30)
	                    END
	            END
	        -- 🔵 MENSUAL
	        WHEN IDTIPONOMINA = 2 THEN 
	            CASE 
	                WHEN MONTH(fechaliquidacion) = 2 THEN 
	                    EOMONTH(fechaliquidacion)
	                ELSE 
	                    DATEFROMPARTS(YEAR(fechaliquidacion),MONTH(fechaliquidacion),30)
	            END
	    END
	FROM dbo.TH_NOMINALIQC
	WHERE IDNOMINALIQC = @IDNOMINA;
	
	IF @ANIO IS NULL OR @MES IS NULL OR @DIA IS NULL
	BEGIN
		SET @MENSAJE = 'PERIODO inválido en TH_NOMINALIQC';
		RETURN;
	END

	DECLARE @charMES char(2) = RIGHT('0' + CAST(MONTH(@FECHAINICIOPERIODO) AS VARCHAR(2)), 2);
	SET @DIAINICIAL = RIGHT('0' + CAST(DAY(@FECHAINICIOPERIODO) AS VARCHAR(2)), 2);
	SET @DIAFINAL   = RIGHT('0' + CAST(DAY(@FECHAFINPERIODO)   AS VARCHAR(2)), 2);

	--Calcular dias a periodo
	SET @DIASPERIODOBASE = 
    CASE 
        WHEN @IDTIPONOMINA = 1 THEN 15
        WHEN @IDTIPONOMINA = 2 THEN 30
    END;
	
	--Traer informacion de riesgos en la db
	DECLARE @INFORIESGO INT =0;

	SELECT @INFORIESGO=COUNT(IDCLASERIESGOARL) FROM TH_DM_CLASERIESGOARL WHERE ANIO=YEAR(@FECHAFINPERIODO)
	
	IF @INFORIESGO=0
	BEGIN
		SET @MENSAJE='No hay informacion de tarifas de clases de riesgos, por favor ingreselos y vuelva a generar la nomina';
	END
	ELSE
	BEGIN 

		--Recorrer personal que se va a incluir en la nomina
		DECLARE CurPersonal CURSOR FOR
		SELECT HV.IDHOJAVIDA,HV.CODIGO,CHV.FECHAINICIO,CHV.SALARIO--,(PA.SALARIOMINIMO*CHV.PORCENTAJESALARIOBASE)
		,CHV.SUBSIDIOTRANSPORTE AS APLICASUBTRAN,IIF(CHV.SUBSIDIOTRANSPORTE=1,PA.SUBSIDIOTRANSPORTE,0) AS SUBSIDIOTRANSPORTE,
		PA.POR_PENSIONES,PA.POR_PENSIONEMPLEADO,PA.POR_SALUD,PA.POR_SALUDEMPLEADO,CARL.VALORINICIAL,PA.POR_CAJA,PA.POR_CESANTIAS,PA.POR_PRIMA,PA.INT_CESANTIAS,PA.POR_VACACIONES,CHV.PORCENTAJESALARIOBASE
		,PA.SALARIOMINIMO,CHV.IDCONTRATOHV
			FROM dbo.TH_HV HV
		INNER JOIN dbo.TH_CONTRATOHV CHV ON CHV.IDHOJAVIDA=HV.IDHOJAVIDA AND CHV.ESTADO=1
		INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.ANIO=YEAR(@FECHAFINPERIODO)
		--INNER JOIN dbo.TH_PARAMETROANUAL PA ON PA.IDPARAMETROANUAL=CHV.IDPARAMETROANUAL
		INNER JOIN dbo.TH_DM_CLASERIESGOARL CARL ON CARL.ANIO=PA.ANIO AND CARL.CODIGO=CHV.CODIGORIESGOARL
		WHERE HV.ESTADOHV=1 --AND CHV.FECHAVENCIMIENTO > GETDATE()
		--AND CHV.IDTIPONOMINA=@IDTIPONOMINA
		AND CHV.FECHAINICIO <  @FECHAFINPERIODO
		OPTION (RECOMPILE)
		--AND HV.IDHOJAVIDA NOT IN (SELECT NB.IDHOJAVIDA FROM TH_NOMINA_BASE NB WHERE IDNOMINA=@IDNOMINA)
		
		OPEN CurPersonal
		FETCH NEXT FROM CurPersonal INTO @IDHOJAVIDA, @CODIGOEMP,@FECHAINICIO, @SALARIO,@APLICASUBTRAN, @SUBSIDIOTRANSPORTE, @POR_PENSIONES, @POR_PENSIONEMPLEADO, @POR_SALUD, @POR_SALUDEMPLEADO, @POR_ARP,@POR_CAJA,@POR_CESANTIAS,@POR_PRIMA,@INT_CESANTIAS,@POR_VACACIONES,@PORCENTAJESALARIOBASE,@SALARIOMINIMOMES,@IDCONTRATOHV

		WHILE (@@FETCH_STATUS = 0) 
		BEGIN
			--PRINT 'COD: '+@CODIGOEMP
			SET @NETOPAGAR=0;
			SET @SUELDOMES =0;
			SET @FECHAINICIOPERIODOHV=@FECHAINICIOPERIODO;
			SET @FECHAFINPERIODOHV=@FECHAFINPERIODO;
			SET @DIASBASEPROVISIONES=0;
			SET @VALOR_ARP=0;
			SET @VALOR_CCF=0;
			SET @VALOR_AFP_EMPLEADOR=0;

			IF @FECHAINICIO > @FECHAINICIOPERIODO AND @FECHAINICIO < @FECHAFINPERIODO
				BEGIN

					SET @DIASPERIODO=dbo.Days360(@FECHAINICIO ,DATEADD(day, 1, @FECHAFINPERIODO))
					SET @FECHAINICIOPERIODOHV=@FECHAINICIO

					/* IF @FECHAFINPERIODOHV=EOMONTH(@FECHAINICIOPERIODOHV) AND MONTH(@FECHAFINPERIODOHV)=2
					BEGIN	
						SET @DIASPERIODO=@DIASPERIODO+(30-DAY(@FECHAFINPERIODO))
					END */

				END
			ELSE	
				BEGIN	
					SET @DIASPERIODO=@DIASPERIODOBASE
					SET @FECHAINICIOPERIODOHV=@FECHAINICIOPERIODO
				END
			
			SET @VALOR_MOV=0
			SET @SUELDOPERIODO = (@SALARIO/30)*@DIASPERIODO
			SET @AUXTRANSPORTEPERIODO = (@SUBSIDIOTRANSPORTE/30)*@DIASPERIODO
			SET @AUXTRANSPORTEBASE = (@SUBSIDIOTRANSPORTE/30)*@DIASPERIODO
			SET @TOTALDEVENGADOPERIODO = @SUELDOPERIODO+@AUXTRANSPORTEPERIODO
			SET @SUELDOPERIODOPROVISIONES = 0;
			
			--PRINT N' CD EMP:'+@CODIGOEMP+' Sueldo:'+STR(@SUELDOPERIODO)+' Aux T:'+STR(@AUXTRANSPORTEPERIODO)+' Periodo:'+STR(@DIA)+' Dias Periodo:'+str(@DIASPERIODO)
		
			-- Novedades Generales
			EXECUTE dbo.sp_TH_NOVEDADES 
								@FECHAINICIOPERIODOHV,
								@FECHAFINPERIODOHV,
								@IDHOJAVIDA,
								@SALARIO,
								@IDNOMINA,
								@SALARIOMINIMOMES,
								@DIASPERIODO OUTPUT,
								@SUBSIDIOTRANSPORTE,
								@SUELDOPERIODO OUTPUT,
								@SUELDOPERIODOPROVISIONES OUTPUT,
								@DIASBASEPROVISIONES OUTPUT,
								@AUXTRANSPORTEPERIODO OUTPUT

			--PRINT N'Aux T1:'+STR(@AUXTRANSPORTEPERIODO)
			-- Descontar Vacaciones
			EXECUTE dbo.sp_TH_PRENOM_REVVACACIONES
								@IDNOMINA,
								@FECHAINICIOPERIODOHV,
								@FECHAFINPERIODOHV,
								@IDHOJAVIDA,
								@SALARIO,
								@DIASPERIODO OUTPUT,
								@SUBSIDIOTRANSPORTE,
								@SUELDOPERIODO OUTPUT,
								@SUELDOPERIODOPROVISIONES OUTPUT,
								@DIASBASEPROVISIONES OUTPUT,
								@AUXTRANSPORTEPERIODO OUTPUT
			--PRINT N'Aux T2:'+STR(@AUXTRANSPORTEPERIODO)	

			IF @SUELDOPERIODOPROVISIONES =0 AND @DIASPERIODO=@DIASBASEPROVISIONES AND (@DIASBASEPROVISIONES=15 OR @DIASBASEPROVISIONES=30 )
				SET @SUELDOPERIODOPROVISIONES = 0;
			ELSE IF @SUELDOPERIODOPROVISIONES =0
			BEGIN
				SET @SUELDOPERIODOPROVISIONES = (@SALARIO/30)*@DIASPERIODO;		
				--Ajuste para validar si vienen novedades full para no pagar parafiscales 
				--No se pagan parafiscales los dias que se tenga novedad
			END	

			SET @VALOR_AFP_EMPLEADOR = @SUELDOPERIODO*(@POR_PENSIONES)/100
			--SET @VALOR_AFP_EMPLEADO = @SUELDOPERIODOPROVISIONES*(@POR_PENSIONEMPLEADO)/100
			SET @VALOR_AFP_EMPLEADO = @SUELDOPERIODO*(@POR_PENSIONEMPLEADO)/100
			SET @VALOR_EPS_EMPLEADOR = (@SUELDOPERIODO*@POR_SALUD)/100
			--SET @VALOR_EPS_EMPLEADO = (@SUELDOPERIODOPROVISIONES*@POR_SALUDEMPLEADO)/100
			SET @VALOR_EPS_EMPLEADO = (@SUELDOPERIODO*@POR_SALUDEMPLEADO)/100
			--SET @VALOR_ARP = (@SUELDOPERIODOPROVISIONES*@POR_ARP)/100
			SET @VALOR_ARP = (@SUELDOPERIODOPROVISIONES*@POR_ARP)/100
			SET @VALOR_CCF = (@SUELDOPERIODOPROVISIONES*@POR_CAJA)/100
			SET @TOTALSALARIOPAGARPERIODO=@SUELDOPERIODO-@VALOR_EPS_EMPLEADO-@VALOR_AFP_EMPLEADO
			SET @TOTALDEVENGADOPERIODOAPORTES = @SUELDOPERIODO+@AUXTRANSPORTEPERIODO
			
			--PRINT N' Dias:'+str(@DIASPERIODO)+' Salud:'+str(@VALOR_EPS_EMPLEADO)+' Pension:'+STR(@VALOR_AFP_EMPLEADO)+' Sal pagar:'+STR(@TOTALSALARIOPAGARPERIODO)
			
			--Guardar Movimientos

			IF @DIASPERIODO >0
			BEGIN
				Declare @IDCONCEPTO INT 
				Declare @CODCONCEPTO VARCHAR(20) 
				--Sueldo  Cod 29
				SET @IDCONCEPTO =29
				SET @CODCONCEPTO ='DV-SUELDOB'
			
				--LIQ D 
				INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
				VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@SUELDOPERIODO,GETDATE(),GETDATE(),'ESPO',0,'510101','250501','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
				SET @TOTALNOMINA=@TOTALNOMINA+ISNULL(@SUELDOPERIODO,0)
				--Auxilio Transporte  Cod 28
				IF @APLICASUBTRAN=1
					BEGIN
						SET @IDCONCEPTO  =28
						SET @CODCONCEPTO  ='DV-SUBTRAN'
						
						--LIQ D 
						INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
						VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@AUXTRANSPORTEPERIODO,GETDATE(),GETDATE(),'ESPO',0,'510123','250501','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
						SET @TOTALNOMINA=@TOTALNOMINA+ISNULL(@AUXTRANSPORTEPERIODO,0)
					END

				--Aportes Pension Empleado
					SET @IDCONCEPTO  =4
					SET @CODCONCEPTO  ='DD-APPENSI'			

					--LIQ D 
					INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
					VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_AFP_EMPLEADO,GETDATE(),GETDATE(),'ESPO',0,'250501','242518','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 
					SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_AFP_EMPLEADO,0)
					-- Revisar si se debe crear movimiento de exceso por vacaciones
					/* IF @DIASBASEPROVISIONES>@DIASPERIODO
					BEGIN
						
						SET @VALOR_AFP_EMPLEADOEXCESO = (@SALARIO/30*(@DIASBASEPROVISIONES-@DIASPERIODO))*(@POR_PENSIONEMPLEADO)/100 
						INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,CLASIFICACION,DIAS)
						VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_AFP_EMPLEADOEXCESO,GETDATE(),GETDATE(),'ESPO',0,'510307','242518','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,'EX',@DIASPERIODO) 
						SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_AFP_EMPLEADOEXCESO,0)
					END */
				--Salud
					SET @IDCONCEPTO  =5
					SET @CODCONCEPTO  ='DD-APSALUD'
					
					--LIQ D 
					SET @FORMULA='VALOR:( Salario:'+STR(@SUELDOPERIODO)+' * % SALUD: '+STR(@POR_SALUDEMPLEADO)+' / 100 ) | Tot:'+STR(@VALOR_EPS_EMPLEADO)
					INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,FORMULAPLICAR,IDCONTRATOHV,DIAS)
					VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_EPS_EMPLEADO,GETDATE(),GETDATE(),'ESPO',0,'250501','242519','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,@DIASPERIODO) 
					SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_EPS_EMPLEADO,0)
					-- Revisar si se debe crear movimiento de exceso por vacaciones
					/* IF @DIASBASEPROVISIONES>@DIASPERIODO
					BEGIN
						SET @IDCONCEPTO  =75
						SET @VALOR_EPS_EMPLEADOEXCESO = (@SALARIO/30*(@DIASBASEPROVISIONES-@DIASPERIODO))*(@POR_PENSIONEMPLEADO)/100 
						SET @FORMULA='VALOR:( Salario:'+CONVERT(varchar,@SALARIO,23)+'/30 *(Dias : Dias Prov:'+CONVERT(varchar,@DIASBASEPROVISIONES,23)+' - dias per:'+STR(@DIASPERIODO)+' ))* % Pension: '+STR(@POR_PENSIONEMPLEADO)+' / 100 ) | Tot:'+STR(@VALOR_EPS_EMPLEADOEXCESO)
						INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,FORMULAPLICAR,IDCONTRATOHV,CLASIFICACION,DIAS)
						VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_EPS_EMPLEADOEXCESO,GETDATE(),GETDATE(),'ESPO',0,'510303','242519','123',GETDATE(),STR(@IDNOMINA),@FORMULA,@IDCONTRATOHV,'EX',@DIASPERIODO) 
						SET @TOTALNOMINA=@TOTALNOMINA-ISNULL(@VALOR_EPS_EMPLEADOEXCESO,0)
					END */

				--Cesantias 
					SET @IDCONCEPTO  =54
					SET @CODCONCEPTO  ='PV-CESANTI'
					SET @VALOR_MOV=ISNULL((@TOTALDEVENGADOPERIODOAPORTES*@POR_CESANTIAS)/100,0)
					
					--LIQ D 
					INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
					VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510124','250801','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

				--Int Cesantias 
					SET @IDCONCEPTO  =55
					SET @CODCONCEPTO  ='PV-INTCESA'
					SET @VALOR_MOV=ISNULL((@VALOR_MOV*@INT_CESANTIAS)/100,0)
					
					--LIQ D 
					INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
					VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510125','250802','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

				--Primas 
					SET @IDCONCEPTO  =56
					SET @CODCONCEPTO  ='PV-PRIMASE'
					SET @VALOR_MOV=ISNULL((@TOTALDEVENGADOPERIODOAPORTES*@POR_PRIMA)/100,0)
					
					--LIQ D 
					INSERT INTO dbo.TH_NOMINALIQD (IDNOMINALIQC,IDHOJAVIDA,IDCONCEPTO,CODIGOCONCEPTO,VALOR,FECHAMOVIMIENTO,FECHA_LIQUIDACION,USUARIO_PRELIQUIDO,CERRADO,CUENTADEBITO,CUENTACREDITO,CENTROCOSTO,FECHAPRELIQUIDACION,DOCUMENTO,IDCONTRATOHV,DIAS)
					VALUES (@IDNOMINA,@IDHOJAVIDA,@IDCONCEPTO,@CODCONCEPTO,@VALOR_MOV,GETDATE(),GETDATE(),'ESPO',0,'510152','250804','123',GETDATE(),STR(@IDNOMINA),@IDCONTRATOHV,@DIASPERIODO) 

				--PV VACACIONES 
					SET @IDCONCEPTO  =57
					SET @CODCONCEPTO  ='PV-VACACIO'
